"""Generate the pagb TM-layer Coq inputs from machine/pa_wade.tm (Wade TMBuilder compile of source_pa.py).

  coq/DagPA.v   : the decision DAG as an RM.prog [dagpa] (node 0 = main().0, registers in declaration order)
  coq/TablePA.v : the literal transition table [pa_table] (trust anchor, checked against the .tm by check_tm.py)
  coq/NamesPA.v : [node_name] / [reg_name] (TM state names; not trusted: ZFTM.v checks [tm] against [pa_table])

Usage: python tools/gen_coq.py        (from zf/pagb/tm; paths are fixed relative to this file)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
TMDIR = os.path.normpath(os.path.join(HERE, '..'))
ZF = os.path.normpath(os.path.join(TMDIR, '..', '..'))
sys.path.insert(0, os.path.join(ZF, 'tools'))
from dag import extract

TM = os.path.join(TMDIR, '..', 'machine', 'pa_wade.tm')
COQ = os.path.join(TMDIR, 'coq')


def main():
    start, tbl, nodes, regidx = extract(TM)
    assert start == '0.boot.A'
    names = sorted(nodes)
    names.remove('main().0')
    names = ['main().0'] + names
    idx = {n: i for i, n in enumerate(names)}
    regs = sorted(regidx, key=regidx.get)

    def coq_edge(e):
        k = e[0]
        if k == 'node':
            return f'ENode {idx[e[1]]}'
        if k == 'op':
            return f"{'EInc' if e[2] == 'inc' else 'EDecnz'} {regidx[e[1]]}"
        if k == 'break':
            return f'EBreak {e[1]}'
        if k == 'continue':
            return f'EContinue {e[1]}'
        if k == 'halt':
            return 'EHalt'
        raise ValueError(e)

    regdoc = ', '.join(f'{r} {i}' for i, r in enumerate(regs))
    L = ['(** Generated by tools/gen_coq.py from machine/pa_wade.tm (Wade TMBuilder compile of source_pa.py)',
         f'    -- do not edit.  {len(names)} decision-DAG nodes; node 0 = main().0 (root).',
         f'    Registers (declaration order): {regdoc}. *)',
         'From PAGBT Require Import RM.', '',
         'Definition dagpa_nodes (n : nat) : edge * edge :=', '  match n with']
    for n in names:
        a, b = nodes[n]
        L.append(f'  | {idx[n]} => ({coq_edge(a)}, {coq_edge(b)})   (* {n} *)')
    L += ['  | _ => (EHalt, EHalt)', '  end.', '',
          f'Definition dagpa : prog := mkProg dagpa_nodes 0 {len(names)}.', '']
    open(os.path.join(COQ, 'DagPA.v'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L))

    T = ['(** Generated by tools/gen_coq.py: the literal transition table of machine/pa_wade.tm -- do not edit.',
         '    Rows (state, read, write, move right?, next state); the start state is 0.boot.A. *)',
         'From Coq Require Import Lists.List Strings.String.',
         'Import ListNotations.', 'Open Scope string_scope.', '',
         'Definition pa_table : list (string * bool * bool * bool * string) := [']
    rows = []
    b = lambda x: 'true' if x else 'false'
    for (s, r), (w, d, n) in sorted(tbl.items()):
        rows.append(f'  ("{s}", {b(r == "1")}, {b(w == "1")}, {b(d == "R")}, "{n}")')
    T.append(';\n'.join(rows))
    T += ['].', '']
    open(os.path.join(COQ, 'TablePA.v'), 'w', encoding='utf-8', newline='\n').write('\n'.join(T))

    N = ['(** Generated by tools/gen_coq.py: TM state names of the DAG nodes and registers -- do not edit.',
         '    Not trusted: ZFTM.v checks the whole machine against [pa_table] by vm_compute. *)',
         'From Coq Require Import Lists.List Strings.String.',
         'Import ListNotations.', 'Open Scope string_scope.', '',
         'Definition reg_name (r : nat) : string :=',
         '  nth r [' + '; '.join(f'"{r}"' for r in regs) + '] "?".', '',
         'Definition node_name (n : nat) : string :=', '  match n with']
    for n in names:
        N.append(f'  | {idx[n]} => "{n}"')
    N += ['  | _ => "?"', '  end.', '']
    open(os.path.join(COQ, 'NamesPA.v'), 'w', encoding='utf-8', newline='\n').write('\n'.join(N))

    states = {s for s, _ in tbl} | {n for _, _, n in tbl.values()}
    print(f'{len(names)} nodes, {len(regs)} registers, {len(tbl)} transitions, {len(states)} states incl. halt')


if __name__ == '__main__':
    main()
