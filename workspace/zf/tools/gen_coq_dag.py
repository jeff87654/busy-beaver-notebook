"""Generate coq/ZF2Dag.v from zf2.tm: the decision DAG as an RM.prog, plus the literal transition table.

Usage: python tools/gen_coq_dag.py ext/turing_machine_explorer/zf2.tm coq/ZF2Dag.v
"""
import sys
sys.path.insert(0, 'tools')
from dag import extract

tmpath, out = sys.argv[1], sys.argv[2]
start, tbl, nodes, regidx = extract(tmpath)
names = sorted(nodes)
names.remove('main().0')
names = ['main().0'] + names            # root = node 0
idx = {n: i for i, n in enumerate(names)}


def coq_edge(e):
    k = e[0]
    if k == 'node':
        return f'ENode {idx[e[1]]}'
    if k == 'op':
        return f"{'EInc' if e[2] == 'inc' else 'EDecnz'} {regidx[e[1]]}"
    if k == 'break':
        return f'EBreak {e[1]}'
    if k == 'continue':
        return f'EContinue {e[1]}'
    if k == 'halt':
        return 'EHalt'
    raise ValueError(e)


lines = []
lines.append('(** Generated by tools/gen_coq_dag.py from zf2.tm — do not edit.')
lines.append(f'    {len(names)} decision-DAG nodes; node 0 = main().0 (root). Registers: {regidx} *)')
lines.append('From Coq Require Import Lists.List Arith.Arith.')
lines.append('From ZF Require Import RM.')
lines.append('Import ListNotations.')
lines.append('')
lines.append('Definition zf2_nodes (n : nat) : edge * edge :=')
lines.append('  match n with')
for n in names:
    a, b = nodes[n]
    lines.append(f'  | {idx[n]} => ({coq_edge(a)}, {coq_edge(b)})   (* {n} *)')
lines.append('  | _ => (EHalt, EHalt)')
lines.append('  end.')
lines.append('')
lines.append(f'Definition zf2 : prog := mkProg zf2_nodes 0 {len(names)}.')
lines.append('')
# literal transition table: list of (state, read, write, dir, next) with states as strings
lines.append('(* literal transition table of zf2.tm, for the equality check against the Coq-built machine *)')
lines.append('Definition zf2_table : list (string * bool * bool * bool * string) := [')
rows = []
for (s, r), (w, d, n) in sorted(tbl.items()):
    rows.append(f'  ("{s}", {"true" if r == "1" else "false"}, {"true" if w == "1" else "false"}, {"true" if d == "R" else "false"}, "{n}")')
lines.append(';\n'.join(rows))
lines.append('].')
text = '\n'.join(lines) + '\n'
# string literals need the String library
text = text.replace('From Coq Require Import Lists.List Arith.Arith.', 'From Coq Require Import Lists.List Arith.Arith Strings.String.\nOpen Scope string_scope.')
open(out, 'w', encoding='utf-8', newline='\n').write(text)
print('wrote', out, len(names), 'nodes', len(tbl), 'transitions; start', start)
