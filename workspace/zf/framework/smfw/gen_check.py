"""Generate frag_check.tm: CHECK = halt iff T_m == e v0 v0 (runs sep1,e3,v0_8,v0_8). Non-destructive."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
L = []
def add(s,r,w,d,n): L.append('%s %s %s %s %s' % (s,r,w,d,n))
# descent: cross marker, cross gap, land on c's rightmost 1
add('check.d0','0','0','L','check.d0'); add('check.d0','1','1','L','check.d1')
add('check.d1','0','0','L','check.d1'); add('check.d1','1','1','L','check.s1')
# scan left to the A|B boundary (first double-0 after c); land on T_m's last token
add('check.s1','1','1','L','check.s1'); add('check.s1','0','0','L','check.s2')
add('check.s2','1','1','L','check.s1'); add('check.s2','0','0','L','check.s3'); add('check.s3','0','0','L','check.v0a1')
MIS='ret.adv.1'   # mismatch = non-destructive advance (no-op)
# verify, reading leftward: v0(8), 0, v0(8), 0, e(3), 0, sep(1), 0 -> halt
runs = [('v0a',8),('v0b',8),('e',3),('sep',1)]
for i,(name,ln) in enumerate(runs):
    last = (i==len(runs)-1)
    nxt = 'halt' if last else ('check.%s1' % runs[i+1][0])
    for j in range(1,ln+1):
        st = 'check.%s%d' % (name,j)
        if j<ln:
            add(st,'1','1','L','check.%s%d'%(name,j+1)); add(st,'0','0','R',MIS)
        else:
            add(st,'1','1','L','check.%s.e'%name); add(st,'0','0','R',MIS)
    # after ln ones, expect a 0 (separator / end); 1 => run too long => mismatch
    add('check.%s.e'%name,'0','0','L' if not last else 'L', nxt if not last else nxt)
    add('check.%s.e'%name,'1','1','R',MIS)
open(os.path.join(HERE,'frag_check.tm'),'w').write(
  '# CHECK (generated by gen_check.py): halt iff T_m == e v0 v0; else no-op advance.\n'
  + '\n'.join(L) + '\n')
print('states:', len(set(x.split()[0] for x in L)), 'lines:', len(L))
