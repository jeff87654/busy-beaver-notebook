"""Collapsed-matrix countermodels: atoms are constants (e_eq for =, e_el for e.), A.x a := Q(a),
-> and -. are finite tables, D the designated set.  Every axiom of `prov` except the target must be
designated for all values of its metavariables in the subalgebra S generated by {e_eq, e_el}; DET and
GEN must preserve designation on S; the target must fail somewhere in S.  Then prov without the target
does not prove the target (every derivable formula is designated)."""
import sys, itertools
sys.path.insert(0, '..'); import lowprio  # noqa

# wff as tuples: ('eq',), ('el',), ('im',a,b), ('n',a), ('al',a)
EQ, EL = ('eq',), ('el',)
def im(a, b): return ('im', a, b)
def n(a): return ('n', a)
def al(a): return ('al', a)
def ex(a): return n(al(n(a)))
def wa(a, b): return n(im(a, n(b)))
PH = ('ph',)
EXT = im(al(wa(im(EL, EL), im(EL, EL))), EQ)
def REP(ph):
    return im(al(ex(al(im(al(ph), EQ)))),
              ex(al(wa(im(EL, ex(wa(EL, al(ph)))), im(ex(wa(EL, al(ph))), EL)))))
POW = ex(al(im(al(im(EL, EL)), EL)))
UNI = ex(al(im(ex(wa(EL, EL)), EL)))
INF = ex(wa(EL, al(im(EL, ex(wa(EL, al(wa(im(EL, EQ), im(EQ, EL)))))))))

def ev(f, M, ph=None):
    I, N, Q, eq, el = M
    t = f[0]
    if t == 'eq': return eq
    if t == 'el': return el
    if t == 'ph': return ph
    if t == 'im': return I[ev(f[1], M, ph)][ev(f[2], M, ph)]
    if t == 'n': return N[ev(f[1], M, ph)]
    return Q[ev(f[1], M, ph)]

def closure(M):
    I, N, Q, eq, el = M
    S = {eq, el}
    while True:
        T = set(S)
        for a in S:
            T.add(N[a]); T.add(Q[a])
            for b in S: T.add(I[a][b])
        if T == S: return sorted(S)
        S = T

def failures(M, D):
    """names of axioms/rules violated on S"""
    I, N, Q, eq, el = M
    S = closure(M); bad = set()
    d = lambda v: v in D
    for a in S:
        if not d(I[I[N[a]][a]][a]): bad.add('B2')
        if not d(I[N[Q[N[Q[a]]]]][a]): bad.add('B6c')
        if not d(I[Q[Q[a]]][Q[Q[a]]]): bad.add('B6b')
        if not d(ev(REP(PH), M, a)): bad.add('REP')
        if d(a) and not d(Q[a]): bad.add('GEN')
        for b in S:
            if not d(I[a][I[N[a]][b]]): bad.add('B3')
            if not d(I[Q[I[a][b]]][I[Q[a]][Q[b]]]): bad.add('B4')
            if d(a) and d(I[a][b]) and not d(b): bad.add('DET')
            for c in S:
                if not d(I[I[a][b]][I[I[b][c]][I[a][c]]]): bad.add('B1')
    if not d(ev(wa(im(EQ, al(EQ)), im(EL, al(EL))), M)): bad.add('B6a')
    if not d(ev(ex(EQ), M)): bad.add('B7')
    if not d(ev(im(EQ, im(EQ, EQ)), M)): bad.add('B8a')
    if not d(ev(im(EQ, im(EL, EL)), M)): bad.add('B8bc')
    for nm, f in (('EXT', EXT), ('POW', POW), ('UNI', UNI), ('INF', INF)):
        if not d(ev(f, M)): bad.add(nm)
    return bad

if __name__ == '__main__':
    nv = int(sys.argv[1]); targets = sys.argv[2].split(',')
    vals = range(nv)
    found = {}
    Ds = [set(c) for r in range(1, nv) for c in itertools.combinations(vals, r)]
    for It in itertools.product(vals, repeat=nv*nv):
        I = [It[i*nv:(i+1)*nv] for i in vals]
        for N in itertools.product(vals, repeat=nv):
            for D in Ds:
                if any(a in D and I[a][b] in D and b not in D for a in vals for b in vals): continue
                pf = set()
                if any(I[I[N[a]][a]][a] not in D for a in vals): pf.add('B2')
                if any(I[a][I[N[a]][b]] not in D for a in vals for b in vals): pf.add('B3')
                if len(pf) > 1: continue
                if any(I[I[a][b]][I[I[b][c]][I[a][c]]] not in D for a in vals for b in vals for c in vals): pf.add('B1')
                if len(pf) > 1: continue
                if pf and not (pf & set(targets)): continue
                for Q in itertools.product(vals, repeat=nv):
                    for eq in vals:
                        for el in vals:
                            M = (I, N, Q, eq, el)
                            bad = failures(M, D)
                            if len(bad) == 1:
                                t = next(iter(bad))
                                if t in targets and t not in found:
                                    found[t] = (I, N, Q, eq, el, sorted(D))
                                    print(t, found[t], flush=True)
                                    if len(found) == len(targets): sys.exit(0)
    print('done; found', sorted(found))
