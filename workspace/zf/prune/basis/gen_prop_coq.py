"""Emit coq/PropBasis.v: for any predicate P closed under DET, {B1, Y} and {B1, B2, B3} derive each other.
usage: python gen_prop_coq.py POLISH_Y"""
import sys
sys.path.insert(0, '..'); import lowprio  # noqa
import cdemit as C
Y = sys.argv[1]
def coqf(t, names):
    return C.coq_term(t, names)
yt = C.parse(Y)
vn = lambda v: 'abc'[v]
def block(axioms, targets, tnames, pfx):
    C.AX = axioms; C.PROV = 'P'; C.PFX = pfx
    thm, found = C.search(targets)
    assert len(found) == len(targets), found
    return C.emit_coq(thm, found, targets, tnames)
hyp = lambda name, t: f'Hypothesis {name} : forall ' + ' '.join('abc'[:C.nvars(t)]) + f' : wff, P {coqf(t, vn)}.'
out = [f'''(** * PropBasis: the propositional axioms B2, B3 can be replaced by the single scheme
    BY = {Y} (Polish notation; p q r = a b c): for any set P of wffs closed under DET,
    {{B1, BY}} derives B2 and B3 (BY from B1-B3: EquivY.v).  Generated by zf/prune/basis/gen_prop_coq.py
    (condensed-detachment derivations). *)
From ZF Require Import Logic.

Definition BYf (a b c : wff) : wff := {coqf(yt, vn)}.

Section FromY.
Variable P : wff -> Prop.
Hypothesis DET : forall a b, P (Wim a b) -> P a -> P b.
{hyp("B1", C.parse("CCpqCCqrCpr"))}
Hypothesis BY : forall a b c : wff, P (BYf a b c).
''']
body = block([('B1', C.parse('CCpqCCqrCpr')), ('BY', yt)], ['CCNppp', 'CpCNpq'], ['y_B2', 'y_B3'], 'yp')
out.append(body)
out.append('End FromY.\n')
src = '\n'.join(out)
open('../coqR3/PropBasis.v', 'w').write(src)
print('written')
