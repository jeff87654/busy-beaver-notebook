def parse(s):
    T = {}
    for i, part in enumerate(s.split('_')):
        st = chr(65 + i)
        for r in range(2):
            t = part[3*r:3*r+3]
            if t[2] in '-Z' or t == '---':
                T[(st, r)] = None
            else:
                T[(st, r)] = (int(t[0]), t[1], t[2])
    return T
