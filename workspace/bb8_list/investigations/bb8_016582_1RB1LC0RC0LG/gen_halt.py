"""Generate the busycoq HALTING proof for 1RB1LC_0RC0LG_1RD0RD_1LE1LD_1RH0LF_---1RA_1RD1RH  (usage: python gen_halt.py out.v)
Phase lemmas are derived by planner8 (explore.py: R1, S6, S3, S1, S4)."""
import sys
import planner8 as pl
from planner8 import drive
import explore as ex
import gen_coq_base as gc

TM = ex.TM
Cdef = lambda l, x, y: 'C %s %s %s' % (l, x, y)
PHASES = [
    ('R1', 'forall l x y, C l (S (S x)) y -->* C l x (8 + y)'),
    ('S6', 'forall l y, C (6 + l) 1 y -->* C (S l) (12 + y) 3'),
    ('S3', 'forall y, C 3 1 y -->* C (9 + y) 7 3'),
    ('S1', 'forall y, C 1 1 y -->* C (11 + y) 7 3'),
]
HALTSTMT = ('S4', 'forall y, C 4 1 y -->* const 0 <{{G}} 1 >> 0 >> 1 >> 1 >> 1 >> 1 >> 1 >> 1 >> 1 >> [1]^^y *> 1 >> 1 >> 1 >> 1 >> 1 >> 1 >> 1 >> const 0')

def s4_target():
    s = ex.PH['S4'][0]
    return pl.step  # unused

def body_for(name, stmt, start, target):
    script, _ = drive(name, start, target, matchers=(), maxev=400, verbose=False)
    tac = gc.script_to_coq(script, False)
    body = 'Lemma %s : %s.\nProof.\n  intros. unfold C.\n' % (name, stmt)
    line = '  '
    for t in tac:
        if len(line) + len(t) > 100:
            body += line.rstrip() + '\n'; line = '  '
        line += t + ' '
    body += line.rstrip() + '\nQed.\n'
    nst = sum(o[1] for o in script if o[0] in ('steps', 'end'))
    print('%-4s literal steps %4d, ops %d' % (name, nst, len(script)), file=sys.stderr)
    return body

def main():
    outp = sys.argv[1]
    pl.set_tm(TM); pl.LEMMAS.clear()
    bodies = []
    for name, stmt in PHASES:
        s, t = ex.PH[name if name in ex.PH else name]
        bodies.append(body_for(name, stmt, s, t))
    # S4: run to the halting configuration
    s = ex.cfg(None, 4, None, 1, 'y', 0)
    c = s
    # advance with planner until halted
    try:
        pl.drive('S4', s, None, maxev=100, verbose=False)
    except pl.Halted as e:
        pass
    # target config = halted config (G reading 0, moving left), see explore output
    tgt = ('G', [pl.BLANK], [1, 0] + [1]*7 + pl.mkrun(ex.ONE, {'y': 1}) + [1]*7 + [pl.BLANK], '<')
    bodies.append(body_for('S4', HALTSTMT[1], s, tgt))
    subst = dict(tm=TM, table=gc.table(TM))
    text = open('halt_head.v.in').read() % subst
    for nm in sorted(pl.LEMMAS):
        text += gc.crossing_lemma(nm, pl.LEMMAS[nm]) + '\n'
    text += '(** ** Phase lemmas (scripts generated by the planner) *)\n\n'
    text += '\n'.join(bodies)
    text += open('halt_tail.v.in').read() % subst
    open(outp, 'w', newline='\n').write(text)
    print('wrote', outp, 'with', len(pl.LEMMAS), 'crossing lemmas', file=sys.stderr)

if __name__ == '__main__':
    main()
