"""gen_fin.py : write dev/Fin.v = the cascade invariant with a FINITE far side (for the ones count at the halt).
reachF Pm L = reachP Pm L /\ fin l, fin l := exists Ll, l = Ll *> const 0.  casc_stepF / reach_topF are the proofs of
Step.casc_stepP / Step.reach_top re-run with the extra conjunct (Step.v itself stays frozen: c04-k31 depends on it)."""
src = open('../dev/Step.v').read()

def block(start):
    b = src[src.index(start):]
    return b[:b.index('Qed.') + 4]

step = block('Theorem casc_stepP')
step = step.replace('Theorem casc_stepP', 'Theorem casc_stepF')
step = step.replace('reachP Pm L -> reachP Pm (gstep L)', 'reachF Pm L -> reachF Pm (gstep L)')
step = step.replace('[t [P [s [y [l [HR [Hy HP]]]]]]]', '[t [P [s [y [l [HR [Hy [HP Hf]]]]]]]]')
step = step.replace('eapply reach_ext; [exact HR | | |].', 'eapply reach_extF; [exact HR | | | |].')
lines = step.split('\n'); out = []
for k, ln in enumerate(lines):
    out.append(ln)
    nxt = lines[k + 1] if k + 1 < len(lines) else ''
    if ln.strip() in ('+ lia.', '+ unfold J. lia.') and (nxt.startswith('  - ') or nxt.startswith('Qed.')):
        out.append('    + fin_tac.')
step = '\n'.join(out)
assert step.count('fin_tac') == 5, step.count('fin_tac')

top = block('Theorem reach_top')
top = top.replace('Theorem reach_top : reachP Pm L1.', 'Theorem reach_topF : reachF Pm L1.')
top = top.replace('split; [| split; [lia | unfold Pm; lia]].',
                  'split; [| split; [lia | split; [unfold Pm; lia | exists (@nil Sym); reflexivity]]].')

HEAD = r'''(** * Fin.v : the cascade invariant with a FINITE far side (generated by gen/gen_fin.py).
    reachF Pm L := reachP Pm L plus  fin l  (l = Ll *> const 0); needed so the halting tape is a finite list (ones). *)
From BB8 Require Import Individual92.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".
From Dev Require Import Base G_rules G_sub2 G_sub3 G_sub4 G_sub5 G_stop G_entry G_top Abs Lift Orbit Chain Step.
Opaque U arrow.

Definition fin (l : side) : Prop := exists Ll : list Sym, l = Ll *> const 0.

Lemma fin_cons : forall (a : Sym) l, fin l -> fin (a >> l).
Proof. intros a l [Ll ->]. exists (a :: Ll). reflexivity. Qed.

Lemma fin_app : forall (xs : list Sym) l, fin l -> fin (xs *> l).
Proof. intros xs l [Ll ->]. exists (xs ++ Ll). rewrite Str_app_assoc. reflexivity. Qed.

Ltac fin_tac := repeat (first [assumption | apply fin_cons | apply fin_app]).

Definition reachF (Pm L : nat) : Prop :=
  exists t P s y l, c0 -->* D0f t (S L) P s y l /\ 1 <= y /\ Pm + L <= P /\ fin l.

Lemma reachF_P : forall Pm L, reachF Pm L -> reachP Pm L.
Proof. intros Pm L [t [P [s [y [l [H1 [H2 [H3 _]]]]]]]]. exists t, P, s, y, l. auto. Qed.

Lemma reach_extF : forall Pm n t P s y l t' P' s' y' l' L',
  c0 -->* D0f t n P s y l -> D0f t n P s y l -->+ D0f t' (S L') P' s' y' l' ->
  1 <= y' -> Pm + L' <= P' -> fin l' -> reachF Pm L'.
Proof.
  intros Pm n t P s y l t' P' s' y' l' L' H1 H2 Hy HP Hf.
  exists t', P', s', y', l'. split; [| split; [assumption | split; assumption]].
  eapply evstep_trans; [exact H1 | apply progress_evstep, H2].
Qed.

'''
open('../dev/Fin.v', 'w', newline='\n').write(HEAD + step + '\n\n' + top + '\n')
print('wrote ../dev/Fin.v')
