"""Assemble the halting proof of T12a as one file.   python gen_final12.py OUT.v
Machine part: gen_machine12 (base rules, n1's round-1 events, restart events, LP1-LP4; generated with the original
mexp settings) and gen_machine_end (round-2-end events; MAXLEN 200), one crossing-lemma set for both."""
import sys, time
from pathlib import Path
from common import *
import mexp
import gen_machine12
import gen_machine_end

TM_S = '1RB0RA_1LC1LF_1RD0LB_1RA1LE_1LI0LC_0RG1LD_1RH1LG_1LC0RG_0LJ0LI_1RK0LC_0RL---_0RF---'
TITLE = 'BB(12) candidate T12a = %s halts' % TM_S
DOC = '''(** Generated by bb8_list/investigations/bb12_t12a_coq (gen_final12.py).  T12a is n1 (Coq-proved 10-state
    f_(omega+1) machine, 1RB0RA_1LC1LF_1RD0LB_1RA1LE_1LI0LC_0RG1LD_1RH1LG_1LC0RG_0LJ0LI_---0LC) with J0 := 1RK and two
    new states K = 0RL---, L = 0RF--- (K1, L1 are the halts).  It runs n1's round 1, restarts in place from the
    accumulator (J0 -> 1RK -> 0RL -> 0RF detours), runs a second full round, and halts on L1 after round 2.
    Machine-level lemmas are generated by mexp.py (specs: gen_base.py, evs.py, evs12.py, evs_end.py); the abstract
    part is abstract.v.in, abstract2_12.v.in, arith.v.in, arith12.v.in, round1_12.v.in, wrappers.v.in,
    restart.v.in, wrappers_end.v.in, end.v.in, end_main.v.in.

    B-form (head in H on the blank right of the word; D(m) = (10)^m 1; tokens nearest-first):
      Bf L ts A = L D(t_1) .. D(t_n) D(0) D(A) H> 0^inf      (ts = [t_n; ..; t_1]).
    Champion rules (as for n1): R1, R2, clearing CLR with U 0 A = 2A+8, U (j+1) A = (U j)^(A/3+1) (4);
    Per L k m n a = [L, 2^k, 5, 1^m, 0, 0, 2, 1^n | a], PERIOD: m -> m - 14 with n' >= F (F n), F n = 2 ^(n arrows) 4.
    Run from the blank tape:
      round 1 (n1's run) up to Bf (FarE k) (1^w ++ [0]) f, w >= F^(2 JJ + 1)(34), JJ = (3T-13)/7, T = 2 ^(37 arrows) 3;
      restart (R1END, E0..E12 with 12 clearings; T12a reads J0 there): Per (lfr [p;3] (FarR k)) 1 (14 J + 3) n a,
        F w <= 7 J + 9;
      round 2 (J periods): Per .. (4 J + 1) 3 n' a', n' >= F^(2 J)(w);
      round-2 end: E20, the depth list becomes n'+1 blocks D3 D2 D0 (one per event), a clearing from 4 at depth 3
        (A24 = iter 3 (U 3) 4 = 40 + 9 y), the blocks are eaten six per loop round (6 cases by the count mod 6),
        then 2-3 continuation events, one or two shallow clearings, and the halt (state L reads 1). *)
'''


def main(out):
    t0 = time.time()
    pl.LEMMAS.clear()
    mexp.MAXLEN, mexp.ROTATE = 64, False
    lem = gen_machine12.gen()
    mexp.MAXLEN, mexp.ROTATE = 200, True
    lem += gen_machine_end.gen()
    mtext = ('\n(** ** Crossing lemmas (generated) *)\n\n' + coqgen.crossing_lemmas()
             + '\n(** ** Machine-level lemmas (generated by mexp.py) *)\n\n' + '\n'.join(lem))
    hdr = header(TITLE).replace(
        '(** Generated by bb8_list/autoproof (engine.py: symbolic execution with automatic loop lemmas; coqgen.py). *)', DOC)
    parts = ['abstract.v.in', 'abstract2_12.v.in', 'arith.v.in', 'arith12.v.in', 'round1_12.v.in']
    text = hdr + '\n' + mtext + ''.join((HERE / f).read_text() for f in parts)
    text += '\n(** *** B-form wrappers of the restart events (generated: gen_wrap.py) *)\n\n' + (HERE / 'wrappers.v.in').read_text()
    text += '\nOpaque U arrow.\n' + (HERE / 'restart.v.in').read_text()
    text += '\n' + (HERE / 'wrap_pre.v.in').read_text()
    text += '\n(** *** B-form wrappers of the round-2-end events (generated: gen_wrap_end.py) *)\n\n' + (HERE / 'wrappers_end.v.in').read_text()
    text += (HERE / 'end.v.in').read_text() + (HERE / 'end_main.v.in').read_text().replace('\nPrint Assumptions halt.\n', '\n')
    Path(out).write_text(text, newline='\n')
    print('wrote', out, len(text), 'bytes (%.1fs)' % (time.time() - t0), file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1])
