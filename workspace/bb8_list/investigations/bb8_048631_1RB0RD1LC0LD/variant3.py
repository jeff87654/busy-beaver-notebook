"""Pipeline for the D0 variants 0RH0RE / 1RB0RE (two-digit counter Q1/Q2).  Run inside a variant directory
with BB8TM set.  Writes the Coq proof to argv[1]."""
import sys, os, pickle
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import planner9 as P
import fam9 as F
import gen_coq as G
from planner9 import C, cadd, cconst, cscale

def Q1(z, x):
    return F.ecfg([('100', z), ('00', 1), ('100', x)])
def Q2(z, x):
    return F.ecfg([('100', z), ('01', 1), ('100', x)])
NAMES = {'z': 'z', 'x': 'x'}

def finish(name, start, target_string, exp):
    script, got = P.drive_until_string2(name, start, target_string, matchers=[F.m_TL], maxev=200000, maxlit=3000000)
    assert script is not None, name
    r = P.normalize_cfg_to(got, exp)
    if r is None:
        print('GOT', got)
        print('EXP', exp)
        print('got', P.show(got))
        print('exp', P.show(exp))
    assert r is not None, name
    cfg2, texts = r
    assert cfg2 == exp
    script = script[:-1] + [('coq', t) for t in texts] + [('stop',)]
    print(name, 'ops', len(script), 'lit', sum(len(o[1]) for o in script if o[0] == 'lits'), 'norm', len(texts))
    return script

# fixed point of the two rounds R1 : Q1(z+1, x+5) -> Q2(z, 3x+18), R2 : Q2(z+3, x+5) -> Q1(z+1, 3x+23)
T1 = P.make_template(Q1(C(0, z=1), C(0, x=1)), NAMES)[0]
for it in range(6):
    s1 = P.instantiate(T1, {'z': C(1, z=1), 'x': C(5, x=1)})
    sc1, got1 = P.drive_until_string2('R1', s1, Q2(C(0, z=1), C(18, x=3)), matchers=[F.m_TL])
    assert sc1 is not None, 'R1'
    T2, m2 = P.make_template(got1, NAMES)
    assert m2 == {'z': C(0, z=1), 'x': C(18, x=3)}, m2
    s2 = P.instantiate(T2, {'z': C(3, z=1), 'x': C(5, x=1)})
    sc2, got2 = P.drive_until_string2('R2', s2, Q1(C(1, z=1), C(23, x=3)), matchers=[F.m_TL])
    assert sc2 is not None, 'R2'
    T1n, m1 = P.make_template(got2, NAMES)
    assert m1 == {'z': C(1, z=1), 'x': C(23, x=3)}, m1
    if repr(T1n) == repr(T1):
        break
    T1 = T1n
else:
    raise SystemExit('no fixed point')
print('fixed point after', it, 'iterations')
# reset R3 : Q2(2, x+5) -> Q2(3x+23, 5)
s3 = P.instantiate(T2, {'z': C(2), 'x': C(5, x=1)})
exp3 = P.instantiate(T2, {'z': C(23, x=3), 'x': C(5)})
sc3 = finish('R3', s3, Q2(C(23, x=3), C(5)), exp3)
# initial segment: blank -> Q2(224, 5) (after the first reset)
s0 = ('A', [P.BLANK], [P.BLANK], '>')
exp0 = P.instantiate(T2, {'z': C(224), 'x': C(5)})
sc0 = finish('INIT', s0, Q2(C(224), C(5)), exp0)

# ---------------------------------------------------------------- Coq
ORIG = '1RB0RD_1LC0LD_1LA1RC_0LB0RE_1LF1RA_1LG---_0LH1LE_0LA0LB'
head = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'coq_head.v.in')).read()
i0 = head.index('(** Formalization of')
i1 = head.index('From BB8 Require Import Individual82.')
head = ('(** * BB(8) holdout variant (D0 of subtask 48631): %s never halts *)\n\n'
        '(** D0 variant of [BB8_48631_1RB0RD.v] (%s).  Generated by ../variant3.py with planner9.py.\n\n'
        '    Here D0 changes the counter: Q1 z x = 0^inf (100)^z 00 (100)^x E> 100110 and\n'
        '    Q2 z x = 0^inf (100)^z 01 (100)^x E> 100110 form a two-digit counter.  Rules (x >= 5):\n'
        '      R1 : Q1 (z+1) x -->+ Q2 z (3x+3)          R2 : Q2 (z+3) x -->+ Q1 (z+1) (3x+8)\n'
        '      R3 : Q2 2 x -->+ Q2 (3x+8) 5              (outer digit exhausted: x becomes the new z)\n'
        '    With D (k, x) = Q2 (3k+2) (x+5): D (k+1, x) -->+ D (k, 9x+67) and D (0, x) -->+ D (x+7, 0).\n'
        '    Q2 always has z = 2 mod 3, so no other ending occurs.  The blank tape reaches\n'
        '    Q2 224 5 = D (74, 0), so the machine never halts. *)\n\n') % (P.TM, ORIG) + head[i1:]
head = head.replace('(* machine: ' + ORIG + ' *)', '(* machine: %s *)' % P.TM)
j0 = head.index('Definition tm : TM')
j1 = head.index('  end.', j0) + len('  end.')
head = head[:j0] + G.tm_def(P.TM) + head[j1:]
out = head
out += '\n(** ** Crossing a run of blocks (generated) *)\n\n'
tlt = G.tl_lemmas()
for nm, lm in sorted(P.LEMMAS.items()):
    out += P.crossing_lemma(nm, lm) + '\n'
out += '\n(** ** The tripling loop TL *)\n\n' + tlt
out += '\n(** ** Families *)\n\n'
out += 'Definition Q1 (z x : nat) : Q * tape :=\n  %s.\n\n' % P.cfg_coq(T1)
out += 'Definition Q2 (z x : nat) : Q * tape :=\n  %s.\n\n' % P.cfg_coq(T2)
out += '\n(** ** Rules *)\n\n'
out += G.evar_lemma('R1', 'forall z x, Q1 (z + 1) (x + 5) -->+ Q2 z (3 * x + 18)', 'Q1', 'Q2', sc1) + '\n'
out += G.evar_lemma('R2', 'forall z x, Q2 (z + 3) (x + 5) -->+ Q1 (z + 1) (3 * x + 23)', 'Q2', 'Q1', sc2) + '\n'
out += G.evar_lemma('R3', 'forall x, Q2 (kN 2) (x + 5) -->+ Q2 (3 * x + 23) (kN 5)', 'Q2', 'Q2', sc3) + '\n'
# INIT
tac = P.script_to_coq(sc0, False)
body = ('Lemma INIT : c0 -->* Q2 (kN 224) (kN 5).\nProof.\n'
        '  change c0 with (A;; const 0 {{0}} const 0). eapply evstep_to_eq.\n  {\n')
line = '    '
for t in tac + ['apply evstep_refl.']:
    if len(line) + len(t) > 110:
        body += line.rstrip() + '\n'
        line = '    '
    line += t + ' '
body += line.rstrip() + '\n  }\n  unfold Q2. first [reflexivity | rewrite ?kN_eq; lia_refl].\nQed.\n'
out += body + '\n'
out += open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'coq_tail3.v.in')).read()
open(sys.argv[1], 'w', newline=chr(10)).write(out)
print('wrote', sys.argv[1])
