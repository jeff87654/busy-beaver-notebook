def park_split(blk, Pb, term):
    """rewrite blk^^(6*p+Pb) into blk^^(Pb-6) *> (blk^^6)^^p *> blk^^6"""
    out = []
    if Pb - 6 > 0:
        out.append('replace (%s) with (%d + (6 * p + 6)) by lia.' % (term, Pb - 6))
        out.append('rewrite (pow_add %s %d (6 * p + 6)).' % (blk, Pb - 6))
    out.append('rewrite (pow_add %s (6 * p) 6), (pow_mul %s 6 p).' % (blk, blk))
    return ' '.join(out)

