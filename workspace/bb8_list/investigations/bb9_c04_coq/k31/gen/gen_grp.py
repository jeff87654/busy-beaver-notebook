"""gen_grp.py base | GROUP : write dev/Base.v (header: tm, notations, normalization tactics) or dev/G_<GROUP>.v
   (Require Base + the group's own crossing/rot lemmas + its machine lemmas).  Groups share the single tm of Base."""
import sys, pickle, time
from common import *
from shapes import *
import mexp, d0spec
HDR_REQ = '''From BB8 Require Import Individual92.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".
From Dev Require Import Base.
'''
def items(group):
    """yield (name, start, target, explore-kwargs, positive)"""
    if group == 'rules':
        import gen_rules, gen_rules_z
        for name, s, t, pos in gen_rules.ITEMS + gen_rules_z.ITEMS:
            yield name, s, t, dict(positive=frozenset(pos)), pos
    elif group == 'reb1':
        import gen_reb1
        yield 'REBUILD1', gen_reb1.START, gen_reb1.TARGET, dict(splits=0, maxstages=400), ()
    elif group.startswith('sub'):
        C = int(group[3:])
        for E in range(6):
            S, Tg, _ = pickle.load(open('tree_sub_%d_%d.pkl' % (C, E), 'rb'))
            yield 'SUB%d_%d' % (C, E), S, Tg, dict(splits=0), ()
    elif group in ('stop', 'entry'):
        for E in range(6):
            S, Tg, _ = pickle.load(open('tree_%s_%d.pkl' % (group, E), 'rb'))
            yield '%s_%d' % (group.upper(), E), S, Tg, dict(splits=0), ()
    else:
        mod = __import__('grp_' + group)          # extra groups: grp_<name>.py with ITEMS = [(name, S, T, kw, pos)]
        for it in mod.ITEMS:
            yield it
def main(group):
    if group == 'base':
        text = header('C04 base: machine, notations, normalization')
        raise SystemExit('k31 copy: never write dev/Base.v')
    pl.LEMMAS.clear(); mexp.ROT_DONE.clear()
    lemmas = []; t0 = time.time()
    for name, S, Tg, kw, pos in items(group):
        tree = mexp.explore(S, Tg, **kw)
        g = mexp.Gen(name.replace('_', ''))
        lemmas += g.lemmas + [mexp.rule_lemma(name, S, Tg, tree, g, progress=True, positive=pos)]
        print('%s: %d lemmas' % (name, len(g.lemmas)), flush=True)
    text = '(** C04 machine lemmas: group %s (generated by gen/gen_grp.py) *)\n\n' % group + HDR_REQ + '\n' \
        + coqgen.crossing_lemmas() + '\n' + '\n'.join(lemmas)
    open('../K_%s.v' % group, 'w', newline='\n').write(text)
    print('wrote K_%s.v %d bytes (%.0fs)' % (group, len(text), time.time() - t0))
if __name__ == '__main__':
    main(sys.argv[1])
