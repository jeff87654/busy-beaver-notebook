import sys
import planner8 as pl
from planner8 import drive
import ex4
from ex1 import m_TRF
from coqgen_lib import script_to_coq, crossing_lemma, table, cl
TM="1RB0LC_0RC0RF_0RD0RH_1LE---_0LF1LG_1RD1LA_1RC1LA_0LF0LA"
S6='[1;1;1;1;1;1]'
def ones(k): return '1 >> '*k
P6='[1;0;1;0;1;0]'
P1='1 >> 0 >> '
PHASES=[
 ('POP',True,"forall t l, (1 >> 0 >> l) {{A}}> 0 >> %s^^t *> %sconst 0 -->+ l {{A}}> 0 >> %s%s^^t *> %sconst 0"%(S6,ones(4),ones(6),S6,ones(4))),
 ('L1',True,"forall j, const 0 {{A}}> 0 >> %s%s^^j *> 1 >> const 0 -->+ (%s^^j *> %s1 >> 1 >> const 0) {{A}}> 0 >> %sconst 0"%(ones(6),S6,P6,P1*4,ones(4))),
 ('L3',True,"forall j, (1 >> 1 >> const 0) {{A}}> 0 >> %s^^j *> %sconst 0 -->+ (1 >> 0 >> 1 >> 1 >> 1 >> 0 >> %s^^j *> %s%s1 >> 1 >> const 0) {{A}}> 0 >> %sconst 0"%(S6,ones(4),P6,P1*3,'',ones(4))),
 ('R0',True,"forall j l, (1 >> 1 >> 1 >> 0 >> 1 >> 0 >> l) {{A}}> 0 >> %s^^j *> %sconst 0 -->+ (%s^^j *> %s1 >> 1 >> 1 >> 0 >> l) {{A}}> 0 >> %sconst 0"%(S6,ones(4),P6,P1*4,ones(4))),
 ('R0e',True,"forall j, (1 >> 1 >> 1 >> 0 >> 1 >> 1 >> const 0) {{A}}> 0 >> %s^^j *> %sconst 0 -->+ (%s^^j *> %s1 >> 1 >> 1 >> 1 >> const 0) {{A}}> 0 >> %sconst 0"%(S6,ones(4),P6,P1*4,ones(4))),
 ('Fin',True,"forall j, (1 >> 1 >> 1 >> 1 >> const 0) {{A}}> 0 >> %s^^j *> %sconst 0 -->+ const 0 {{A}}> 0 >> %s%s^^j *> %sconst 0"%(S6,ones(4),ones(9),S6,ones(4))),
]
def main():
    outp=sys.argv[1]
    pl.set_tm(TM); pl.LEMMAS.clear()
    bodies=[]
    for name,progress,stmt in PHASES:
        start,target=ex4.PH[name]
        script,_=drive(name,start,target,matchers=[m_TRF],maxev=400,verbose=False)
        assert script[-1][0]=='end', (name,script[-1])
        tac=script_to_coq(script,progress)
        body='Lemma %s : %s.\nProof.\n  intros.\n'%(name,stmt)
        line='  '
        for t in tac:
            if len(line)+len(t)>100:
                body+=line.rstrip()+'\n'; line='  '
            line+=t+' '
        body+=line.rstrip()+'\nQed.\n'
        bodies.append(body)
    head=open('head.v.in').read()%dict(tm=TM,table=table(TM))
    text=head
    for nm in sorted(pl.LEMMAS):
        text+=crossing_lemma(nm,pl.LEMMAS[nm])+'\n'
    text+=open('trf.v.in').read()
    text+='(** ** Phase lemmas (scripts generated by the planner) *)\n\n'+'\n'.join(bodies)
    text+=open('tail.v.in').read()%dict(init=0)
    open(outp,'w',newline='\n').write(text)
main()
