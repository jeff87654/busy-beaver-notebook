"""Machine-level lemmas for 1RB0RA_1LC1LF_1RD0LB_1RA1LE_0LI0LC_1RG1LD_1LC0RH_1RG1LF_---0LA.
  python gen_machine.py OUT.v      (development file: header + ported BB(8) lemmas + generated lemmas)
Returns (via gen()) the text of the machine part, used by gen_final.py."""
import re, sys, time, pickle
from pathlib import Path
from common import *
import mexp
from handloop import make_loop
from st0 import START as S0_START, TARGET as S0_TARGET
from p3loop3 import X3, E2

PROOFS = HERE.parents[1] / 'proofs'
SUBST = engine.subst


def ported():
    """BB8_champ35_1RB0RA.v crossings and phases (renamed h_*), FINx from BB8_champ35_bound.v."""
    src = (PROOFS / 'BB8_champ35_1RB0RA.v').read_text()
    a = src.index('(** crossings *)')
    b = src.index('Lemma FIN :')
    text = src[a:b]
    bnd = (PROOFS / 'BB8_champ35_bound.v').read_text()
    c = bnd.index('(** The configuration reached by the imported phase [FIN]')
    d = bnd.index('(** [R4] of the halting file')
    text += bnd[c:d]
    text = text.replace('Lemma c_end_halted : forall J t, halted tm (c_end J t).\nProof. intros. unfold c_end. simpl. reflexivity. Qed.\n', '')
    for nm in ['ROUND', 'R1F', 'R2F', 'E3', 'HOP', 'X3', 'X4', 'TLP', 'FINx']:
        text = re.sub(r'\b%s\b' % nm, 'h8_' + nm, text)
    text = re.sub(r'\b(cr|cx)_', r'h8\1_', text)
    text = text.replace('finish_norm', 'finish_norm8')
    text = text.replace('(** [FIN] of the halting file with its existential witness made explicit (same tactic script). *)',
                        '(** [FIN] of BB8_champ35_1RB0RA.v, ending where the 8-state machine halts (E reading 0; here E0 = 0LI). *)')
    hdr = ("(** ** Ported from BB8_champ35_1RB0RA.v / BB8_champ35_bound.v (the machines agree on every transition used) *)\n\n"
           "Ltac finish_norm8 := apply evstep_refl'; norm_nat; align_tape; try reflexivity; lia_refl.\n\n")
    return hdr + text


def gen():
    lemmas = []
    t0 = time.time()
    # stage 0: c_end J (5n+1) -->* Kr (1^(2n+J) ++ 7 :: 6 :: 8 :: 9^n) 1 0
    tree = mexp.explore(S0_START, S0_TARGET, splits=0)
    g = mexp.Gen('S0')
    lemmas += [None]
    rule = mexp.rule_lemma('STAGE0', S0_START, S0_TARGET, tree, g, progress=False)
    lemmas = g.lemmas + [rule]
    # stage 2a: Kr ((1^5)^u ++ 0 :: 8 :: l) 1 r -->* E2
    S2 = KR(tok(1), tok(1, 'r'), [run(Z * 5, u=1)] + tok(0) + tok(8) + [V('l')])
    tree = mexp.explore(S2, E2, splits=0)
    g = mexp.Gen('S2A')
    lemmas += g.lemmas[:0]
    rule = mexp.rule_lemma('ST2A', S2, E2, tree, g, progress=False)
    lemmas += g.lemmas + [rule]
    # stage 2b: E2 (u = S w) -->* X3 w 0
    P = SUBST(E2, 'u', (('w', 1),), 1)
    T = SUBST(SUBST(X3('w', 'i'), 'i', (), 0), 'w', (('w', 1),), 0)
    tree = mexp.explore(P, T, splits=0)
    g = mexp.Gen('S2B')
    rule = mexp.rule_lemma('ST2B', P, T, tree, g, progress=False)
    lemmas += g.lemmas + [rule]
    # stage 2 loop: X3 v i -->* X3 0 (i + v)
    lp = make_loop(X3(), 'v', ['i'], ((('v', 1),), 0))
    g = mexp.Gen('S2L')
    lname, binders = g.loop(lp)
    lemmas += g.lemmas
    loop_stmt = (lname, binders)
    # stage 2c: X3 0 i -->* halt
    X0 = SUBST(X3(), 'v', (), 0)
    tree = mexp.explore(X0, None, splits=0)
    assert tree.get('halt') and all(it[0] != 'split' for it in tree['items'])
    g = mexp.Gen('S2C')
    tac = ['intros.']
    for it in tree['items']:
        if it[0] == 'ops':
            tac.append(g.stage(it[2], it[1], it[3]))
        else:
            tac.append(g.use_loop(it[1]))
    end = tree['end']
    cn, vs = coqgen.free_vars(X0, end)
    lemmas += g.lemmas
    lemmas.append('Lemma ST2C : forall %s, %s -->* %s.\nProof.\n%s\n  finish_norm.\nQed.\n'
                  % (' '.join(cn + vs), coqgen.cfg_coq(X0), coqgen.cfg_coq(end), coqgen.wrap(tac)))
    lemmas.append('Lemma ST2C_halted : forall %s, halted tm (%s).\nProof. intros. reflexivity. Qed.\n'
                  % (' '.join(cn + vs), coqgen.cfg_coq(end)))
    info = dict(loop=loop_stmt, end=end, X0=X0, S2=S2, E2=E2, P=P, T=T)
    pickle.dump(info, open('machine_info.pkl', 'wb'))
    print('generated in %.1fs, %d lemmas' % (time.time() - t0, len(lemmas)), file=sys.stderr)
    print('loop lemma:', loop_stmt, file=sys.stderr)
    return lemmas


def machine_text():
    pl.LEMMAS.clear()
    lem = gen()
    return (ported() + '\n(** ** Crossing lemmas (generated) *)\n\n' + coqgen.crossing_lemmas()
            + '\n(** ** Machine-level lemmas (generated by mexp.py) *)\n\n' + '\n'.join(lem))


if __name__ == '__main__':
    text = header('machine part (development)') + '\n' + machine_text()
    Path(sys.argv[1]).write_text(text, newline='\n')
    print('wrote', sys.argv[1], len(text), 'bytes', file=sys.stderr)
