"""Generate the busycoq proof BB8_048631_1RB0RG.v for 1RB0RG_1LC1RE_1LD0LD_0RA1LC_0RF0LC_1LG1RH_1LB1RG_1RF---.

    python gen048.py OUT.v
Phase scripts come from planner8.drive (exact symbolic execution); the rest of the file is hand-written (head048.v.in, tail048.v.in).
"""
import os, sys
NL = chr(10)
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import planner8 as pl
from planner8 import drive, BLANK, mkrun, V
from coqgen_util import script_to_coq, crossing_lemma, table

TM = '1RB0RG_1LC1RE_1LD0LD_0RA1LC_0RF0LC_1LG1RH_1LB1RG_1RF---'
U = (0, 1)
HL = [0, 1, 1, 0, V('l')]

def phases():
    return [
        ('R1P',
         ('A', [BLANK], [0, 1, 1, 1] + mkrun(U, {'b': 1}) + [0, 0, 1, 0, V('l')], '>'),
         ('A', [BLANK], [0, 1, 1, 1] + mkrun(U, {'b': 1}, 1) + [0, 0, V('l')], '>'),
         'forall b l, (const 0) {{A}}> (0 >> 1 >> 1 >> 1 >> [0;1]^^b *> 0 >> 0 >> 1 >> 0 >> l) -->+ '
         '(const 0) {{A}}> (0 >> 1 >> 1 >> 1 >> 0 >> 1 >> [0;1]^^b *> 0 >> 0 >> l)'),
        ('TR0',
         ('A', [BLANK], [0, 1, 1, 1] + mkrun(U, {'r': 1}, 1) + [0, 0, 0, V('w')], '>'),
         ('A', [0, 1, 1, BLANK], mkrun(U, {'r': 1}, 2) + [0, 0, V('w')], '>'),
         'forall r w, (const 0) {{A}}> (0 >> 1 >> 1 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 0 >> w) -->+ '
         '(0 >> 1 >> 1 >> const 0) {{A}}> (0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> w)'),
        ('LOOP',
         ('A', [V('l')], mkrun(U, {'r': 1}, 2) + [0, 0, 0, V('w')], '>'),
         ('A', [0, 1, 1, V('l')], mkrun(U, {'r': 1}, 1) + [0, 0, V('w')], '>'),
         'forall r l w, l {{A}}> (0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 0 >> w) -->+ '
         '(0 >> 1 >> 1 >> l) {{A}}> (0 >> 1 >> [0;1]^^r *> 0 >> 0 >> w)'),
        ('FINS',
         ('A', HL, mkrun(U, {'r': 1}, 2) + [0, 0, 1, 0, 1] + mkrun(U, {'y': 1}) + [V('rr')], '>'),
         ('A', HL, [0, 1, 1, 1] + mkrun(U, {'r': 1}, 1) + [0, 0, 1] + mkrun(U, {'y': 1}) + [V('rr')], '>'),
         'forall r y l rr, (0 >> 1 >> 1 >> 0 >> l) {{A}}> '
         '(0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 1 >> 0 >> 1 >> [0;1]^^y *> rr) -->+ '
         '(0 >> 1 >> 1 >> 0 >> l) {{A}}> '
         '(0 >> 1 >> 1 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 1 >> [0;1]^^y *> rr)'),
        ('FINZ',
         ('A', HL, mkrun(U, {'r': 1}, 2) + [0, 0, 1, 0, V('rr')], '>'),
         ('A', HL, [0, 1, 1, 1] + mkrun(U, {'r': 1}, 1) + [0, 0, V('rr')], '>'),
         'forall r l rr, (0 >> 1 >> 1 >> 0 >> l) {{A}}> '
         '(0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 1 >> 0 >> rr) -->+ '
         '(0 >> 1 >> 1 >> 0 >> l) {{A}}> '
         '(0 >> 1 >> 1 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> rr)'),
        ('TRN',
         ('A', HL, [0, 1, 1, 1, V('w')], '>'),
         ('A', [0, V('l')], [0, 1, 1, 1, 0, 0, 1, V('w')], '>'),
         'forall l w, (0 >> 1 >> 1 >> 0 >> l) {{A}}> (0 >> 1 >> 1 >> 1 >> w) -->+ '
         '(0 >> l) {{A}}> (0 >> 1 >> 1 >> 1 >> 0 >> 0 >> 1 >> w)'),
        ('END',
         ('A', HL, [0, 1, BLANK], '>'),
         ('A', [0, V('l')], [0, 1, 1, 1, 0, 0, 1, BLANK], '>'),
         'forall l, (0 >> 1 >> 1 >> 0 >> l) {{A}}> (0 >> 1 >> const 0) -->+ '
         '(0 >> l) {{A}}> (0 >> 1 >> 1 >> 1 >> 0 >> 0 >> 1 >> const 0)'),
    ]

def gen(outp):
    pl.set_tm(TM)
    pl.LEMMAS.clear()
    bodies = []
    for name, start, target, stmt in phases():
        script, _ = drive(name, start, target, matchers=(), maxev=400, verbose=False)
        if script[-1][0] != 'end':
            raise SystemExit('planner did not reach target of %s: %r' % (name, script[-3:]))
        tac = script_to_coq(script, True)
        if len(script) == 1 and script[0][0] == 'end':
            tac = ['start_progress.']
        body = 'Lemma %s : %s.\nProof.\n  intros.\n' % (name, stmt)
        line = '  '
        for t in tac:
            if len(line) + len(t) > 100:
                body += line.rstrip() + NL
                line = '  '
            line += t + ' '
        body += line.rstrip() + '\nQed.\n'
        bodies.append(body)
        nst = sum(o[1] for o in script if o[0] in ('steps', 'end'))
        print('  %-6s literal steps %4d, ops %d' % (name, nst, len(script)), file=sys.stderr)
    crossings = ''.join(crossing_lemma(nm, pl.LEMMAS[nm]) + NL for nm in sorted(pl.LEMMAS))
    head = open(os.path.join(HERE, 'head048.v.in')).read()
    tail = open(os.path.join(HERE, 'tail048.v.in')).read()
    text = head.replace('@TABLE@', table(TM)).replace('@TM@', TM) + '\n(** ** Crossing lemmas (generated) *)\n\n' + crossings \
        + '\n(** ** Phase lemmas (scripts generated by the planner) *)\n\n' + '\n'.join(bodies) + tail
    open(outp, 'w', newline=NL).write(text)
    print('wrote', outp, file=sys.stderr)

if __name__ == '__main__':
    gen(sys.argv[1])
