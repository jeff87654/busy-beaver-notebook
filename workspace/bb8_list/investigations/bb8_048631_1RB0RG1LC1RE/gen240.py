"""Generate the busycoq proof BB8_240161_1RB0RA.v for 1RB0RA_0RC0RD_0LD---_1RE0LF_1RF1RD_1LE0LG_1LF1LH_0RA0LG.

    python gen240.py OUT.v
Phase scripts come from planner8.drive (exact symbolic execution); the rest of the file is hand-written (HEAD/TAIL below).
"""
import os, sys
NL = chr(10)
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import planner8 as pl
from planner8 import drive, BLANK, mkrun, V
from coqgen_util import script_to_coq, crossing_lemma, table

TM = '1RB0RA_0RC0RD_0LD---_1RE0LF_1RF1RD_1LE0LG_1LF1LH_0RA0LG'
U = (0, 1)

def phases():
    L100 = mkrun((1, 0, 0), {'j': 1})
    return [
        ('R1P',
         ('E', [BLANK], [0, 1, 1] + mkrun(U, {'b': 1}) + [0, 0, 1, V('l')], '>'),
         ('E', [BLANK], [0, 1, 1] + mkrun(U, {'b': 1}, 2) + [0, V('l')], '>'),
         'forall b l, (const 0) {{E}}> (0 >> 1 >> 1 >> [0;1]^^b *> 0 >> 0 >> 1 >> l) -->+ '
         '(const 0) {{E}}> (0 >> 1 >> 1 >> 0 >> 1 >> 0 >> 1 >> [0;1]^^b *> 0 >> l)'),
        ('TR',
         ('E', [BLANK], [0, 1, 1] + mkrun(U, {'b': 1}) + [0, 0, 0, V('rr')], '>'),
         ('H', [1, BLANK], [0, 1] + mkrun(U, {'b': 1}) + [0, 0, V('rr')], '>'),
         'forall b rr, (const 0) {{E}}> (0 >> 1 >> 1 >> [0;1]^^b *> 0 >> 0 >> 0 >> rr) -->+ '
         '(1 >> const 0) {{H}}> (0 >> 1 >> [0;1]^^b *> 0 >> 0 >> rr)'),
        ('LOOP',
         ('H', [1, V('l')], [0, 1] + mkrun(U, {'r': 1}, 1) + [0, 0, 0, V('rr')], '>'),
         ('H', [1, 0, 0, 1, V('l')], [0, 1] + mkrun(U, {'r': 1}) + [0, 0, V('rr')], '>'),
         'forall r l rr, (1 >> l) {{H}}> (0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 0 >> rr) -->+ '
         '(1 >> 0 >> 0 >> 1 >> l) {{H}}> (0 >> 1 >> [0;1]^^r *> 0 >> 0 >> rr)'),
        ('FINAL',
         ('H', L100 + [1, BLANK], [0, 1] + mkrun(U, {'r': 1}, 1) + [0, 0, 1] + mkrun(U, {'y': 1}) + [V('rr')], '>'),
         ('E', [BLANK], [0, 1, 1] + mkrun((0, 0, 1), {'j': 1}) + [0] + mkrun(U, {'r': 1}, 3) + [0]
          + mkrun(U, {'y': 1}) + [V('rr')], '>'),
         'forall j r y rr, ([1;0;0]^^j *> 1 >> const 0) {{H}}> '
         '(0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> 0 >> 1 >> [0;1]^^y *> rr) -->+ '
         '(const 0) {{E}}> (0 >> 1 >> 1 >> [0;0;1]^^j *> 0 >> 0 >> 1 >> 0 >> 1 >> 0 >> 1 >> [0;1]^^r *> 0 >> '
         '[0;1]^^y *> rr)'),
        ('END4',
         ('H', L100 + [1, BLANK], [0, 1, BLANK], '>'),
         ('E', [BLANK], [0, 1, 1] + mkrun((0, 0, 1), {'j': 1}) + [0, 0, 1, 0, 1, BLANK], '>'),
         'forall j, ([1;0;0]^^j *> 1 >> const 0) {{H}}> (0 >> 1 >> const 0) -->+ '
         '(const 0) {{E}}> (0 >> 1 >> 1 >> [0;0;1]^^j *> 0 >> 0 >> 1 >> 0 >> 1 >> const 0)'),
    ]

def gen(outp):
    pl.set_tm(TM)
    pl.LEMMAS.clear()
    bodies = []
    for name, start, target, stmt in phases():
        script, _ = drive(name, start, target, matchers=(), maxev=400, verbose=False)
        if script[-1][0] != 'end':
            raise SystemExit('planner did not reach target of %s: %r' % (name, script[-3:]))
        tac = script_to_coq(script, True)
        body = 'Lemma %s : %s.\nProof.\n  intros.\n' % (name, stmt)
        line = '  '
        for t in tac:
            if len(line) + len(t) > 100:
                body += line.rstrip() + NL
                line = '  '
            line += t + ' '
        body += line.rstrip() + '\nQed.\n'
        bodies.append(body)
        nst = sum(o[1] for o in script if o[0] in ('steps', 'end'))
        print('  %-6s literal steps %4d, ops %d' % (name, nst, len(script)), file=sys.stderr)
    crossings = ''.join(crossing_lemma(nm, pl.LEMMAS[nm]) + NL for nm in sorted(pl.LEMMAS))
    head = open(os.path.join(HERE, 'head240.v.in')).read()
    tail = open(os.path.join(HERE, 'tail240.v.in')).read()
    text = head.replace('@TABLE@', table(TM)).replace('@TM@', TM) + '\n(** ** Crossing lemmas (generated) *)\n\n' + crossings \
        + '\n(** ** Phase lemmas (scripts generated by the planner) *)\n\n' + '\n'.join(bodies) + tail
    open(outp, 'w', newline=NL).write(text)
    print('wrote', outp, file=sys.stderr)

if __name__ == '__main__':
    gen(sys.argv[1])
