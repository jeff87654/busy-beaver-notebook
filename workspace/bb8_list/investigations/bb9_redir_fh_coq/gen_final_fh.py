def main(out, dev):
    cfg = pickle.load(open('cfgs_fh.pkl', 'rb'))
    B12 = [t for t in cfg['E0'][1] if isinstance(t, tuple) and t[0] == 'run'][0][1]
    run_ = Path('run_fh.v.in').read_text()
    run_ = run_.replace('@MRC@', coqgen.cfg_coq(cfg['MR'])).replace('@YC@', coqgen.cfg_coq(cfg['Y']))
    run_ = run_.replace('@E0C@', coqgen.cfg_coq(cfg['E0'])).replace('@HOP@', cfg['hop'][0])
    run_ = run_.replace('@B12@', '[' + ';'.join(map(str, B12)) + ']')
    abstract = Path('abstract_fh_base.v.in').read_text() + run_ + Path('arith_fh.v.in').read_text() + Path('main_fh.v.in').read_text()
    if dev:
        pre = 'From BB8 Require Import Individual92.\nFrom Dev Require Import M.\nFrom Coq Require Import Lia PeanoNat List.\nImport ListNotations.\nSet Default Goal Selector "!".\n'
        Path(out).write_text(pre + abstract + '\nPrint Assumptions halt.\n', newline='\n')
    else:
        import gen_machine_fh
        mtext = gen_machine_fh.machine_text()
        hdr = header(TITLE).replace('(** Generated by bb8_list/autoproof (engine.py: symbolic execution with automatic loop lemmas; coqgen.py). *)', DOC)
        Path(out).write_text(hdr + '\n' + mtext + abstract, newline='\n')
    print('wrote', out)
if __name__ == '__main__':
    main(sys.argv[1], '--dev' in sys.argv)
