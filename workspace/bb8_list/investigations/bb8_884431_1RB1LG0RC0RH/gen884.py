"""Generate the busycoq proof BB8_884431_1RB1LG_0RC0RH.v for 1RB1LG_0RC0RH_1RD0RE_1LE---_1RF1RE_0LA0LG_1LH1LA_0RA0LA.

    python gen884.py OUT.v [TM]
Phase scripts come from planner8.drive (exact symbolic execution); the rest of the file is hand-written (head884.v.in, tail884.v.in).
"""
import os, sys
NL = chr(10)
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import planner8 as pl
from planner8 import drive, BLANK, mkrun, V
from coqgen_util import script_to_coq, crossing_lemma, table

TM0 = '1RB1LG_0RC0RH_1RD0RE_1LE---_1RF1RE_0LA0LG_1LH1LA_0RA0LA'
U = (1, 1)

def phases():
    B0 = [0, 1, 1, 0, 1, BLANK]
    S4 = [0, 1, 1, 0, V('l')]
    return [
        ('R1P',
         ('A', [BLANK], [0, 0, 1, 1] + mkrun(U, {'b': 1}) + [0, 1, V('l')], '>'),
         ('A', [BLANK], [0, 0, 1, 1, 1, 1] + mkrun(U, {'b': 1}) + [0, V('l')], '>'),
         'forall b l, (const 0) {{A}}> (0 >> 0 >> 1 >> 1 >> [1;1]^^b *> 0 >> 1 >> l) -->+ '
         '(const 0) {{A}}> (0 >> 0 >> 1 >> 1 >> 1 >> 1 >> [1;1]^^b *> 0 >> l)'),
        ('TR',
         ('A', [BLANK], [0, 0, 1, 1] + mkrun(U, {'c': 1}) + [0, 0, V('w')], '>'),
         ('C', B0, mkrun(U, {'c': 1}) + [0, V('w')], '>'),
         'forall c w, (const 0) {{A}}> (0 >> 0 >> 1 >> 1 >> [1;1]^^c *> 0 >> 0 >> w) -->+ '
         '(0 >> 1 >> 1 >> 0 >> 1 >> const 0) {{C}}> ([1;1]^^c *> 0 >> w)'),
        ('LOOP',
         ('C', S4, [1, 1] + mkrun(U, {'r': 1}) + [0, 0, V('w')], '>'),
         ('C', [0, 1, 1, 0, 1, 1, 0, V('l')], mkrun(U, {'r': 1}) + [0, V('w')], '>'),
         'forall r l w, (0 >> 1 >> 1 >> 0 >> l) {{C}}> (1 >> 1 >> [1;1]^^r *> 0 >> 0 >> w) -->+ '
         '(0 >> 1 >> 1 >> 0 >> 1 >> 1 >> 0 >> l) {{C}}> ([1;1]^^r *> 0 >> w)'),
        ('FINA',
         ('C', S4, [1, 1] + mkrun(U, {'r': 1}) + [0, 1, V('w')], '>'),
         ('A', S4, [1, 1, 1] + mkrun(U, {'r': 1}) + [0, V('w')], '>'),
         'forall r l w, (0 >> 1 >> 1 >> 0 >> l) {{C}}> (1 >> 1 >> [1;1]^^r *> 0 >> 1 >> w) -->+ '
         '(0 >> 1 >> 1 >> 0 >> l) {{A}}> (1 >> 1 >> 1 >> [1;1]^^r *> 0 >> w)'),
        ('FINB0',
         ('A', B0, [1, 1, 1] + mkrun(U, {'r': 1}) + [0, V('w')], '>'),
         ('A', [BLANK], [0, 0, 1, 1, 0] + mkrun(U, {'r': 1}) + [1, 1, 1, 1, 0, V('w')], '>'),
         'forall r w, (0 >> 1 >> 1 >> 0 >> 1 >> const 0) {{A}}> (1 >> 1 >> 1 >> [1;1]^^r *> 0 >> w) -->+ '
         '(const 0) {{A}}> (0 >> 0 >> 1 >> 1 >> 0 >> [1;1]^^r *> 1 >> 1 >> 1 >> 1 >> 0 >> w)'),
        ('FINBT',
         ('A', [0, 1, 1] + mkrun((0, 1, 1), {'t': 1}) + B0, [1, 1, 1] + mkrun(U, {'r': 1}) + [0, V('w')], '>'),
         ('A', [BLANK], [0, 0, 1, 1, 0, 1, 1, 0] + mkrun((1, 1, 0), {'t': 1}) + mkrun(U, {'r': 1})
          + [1, 1, 1, 1, 0, V('w')], '>'),
         'forall t r w, (0 >> 1 >> 1 >> [0;1;1]^^t *> 0 >> 1 >> 1 >> 0 >> 1 >> const 0) {{A}}> '
         '(1 >> 1 >> 1 >> [1;1]^^r *> 0 >> w) -->+ '
         '(const 0) {{A}}> (0 >> 0 >> 1 >> 1 >> 0 >> 1 >> 1 >> 0 >> [1;1;0]^^t *> [1;1]^^r *> 1 >> 1 >> 1 >> 1 >> 0 >> w)'),
        ('END4',
         ('C', mkrun((0, 1, 1), {'t': 1}) + B0, [BLANK], '>'),
         ('A', [BLANK], [0, 0, 1, 1, 0] + mkrun((1, 1, 0), {'t': 1}) + [1, 1, 1, 1, 0, BLANK], '>'),
         'forall t, ([0;1;1]^^t *> 0 >> 1 >> 1 >> 0 >> 1 >> const 0) {{C}}> const 0 -->+ '
         '(const 0) {{A}}> (0 >> 0 >> 1 >> 1 >> 0 >> [1;1;0]^^t *> 1 >> 1 >> 1 >> 1 >> 0 >> const 0)'),
    ]

def gen(outp, TM=TM0):
    pl.set_tm(TM)
    pl.LEMMAS.clear()
    bodies = []
    for name, start, target, stmt in phases():
        script, _ = drive(name, start, target, matchers=(), maxev=400, verbose=False)
        if script[-1][0] != 'end':
            raise SystemExit('planner did not reach target of %s: %r' % (name, script[-3:]))
        tac = script_to_coq(script, True)
        body = 'Lemma %s : %s.\nProof.\n  intros.\n' % (name, stmt)
        line = '  '
        for t in tac:
            if len(line) + len(t) > 100:
                body += line.rstrip() + NL
                line = '  '
            line += t + ' '
        body += line.rstrip() + '\nQed.\n'
        bodies.append(body)
        nst = sum(o[1] for o in script if o[0] in ('steps', 'end'))
        print('  %-6s literal steps %4d, ops %d' % (name, nst, len(script)), file=sys.stderr)
    crossings = ''.join(crossing_lemma(nm, pl.LEMMAS[nm]) + NL for nm in sorted(pl.LEMMAS))
    head = open(os.path.join(HERE, 'head884.v.in')).read()
    tail = open(os.path.join(HERE, 'tail884.v.in')).read()
    text = head.replace('@TABLE@', table(TM)).replace('@TM@', TM) + '\n(** ** Crossing lemmas (generated) *)\n\n' + crossings \
        + '\n(** ** Phase lemmas (scripts generated by the planner) *)\n\n' + '\n'.join(bodies) + tail
    open(outp, 'w', newline=NL).write(text)
    print('wrote', outp, file=sys.stderr)

if __name__ == '__main__':
    gen(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else TM0)
