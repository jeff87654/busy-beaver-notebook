import idle, pidrec
"""xgrp.py GROUP : write ../x/dev/G_<GROUP>.v for the machine X (raw X steps: the file redefines [step] as [step1]).
   Items from grp_<GROUP>.py (ITEMS = [(name, S, T, explore-kwargs, positive)])."""
import sys, time, os
from common import *
from shapes import *
import mexp
HDR_REQ = '''From XL Require Import Individual112.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".
From XDev Require Import Base.
(* The generated scripts below count raw X3 steps. *)
Ltac step := step1.
'''
def main(group):
    pl.LEMMAS.clear(); mexp.ROT_DONE.clear()
    mod = __import__('grp_' + group)
    lemmas = []; t0 = time.time()
    for name, S, Tg, kw, pos in mod.ITEMS:
        tree = mexp.explore(S, Tg, **kw)
        g = mexp.Gen(name.replace('_', ''))
        lemmas += g.lemmas + [mexp.rule_lemma(name, S, Tg, tree, g, progress=True, positive=pos)]
        print('%s: %d lemmas (%.0fs)' % (name, len(g.lemmas), time.time() - t0), flush=True)
    text = ('(** X3 machine lemmas: group %s (generated by gen/xgrp.py, mexp retargeted to X3) *)\n\n' % group) + HDR_REQ + '\n' \
        + coqgen.crossing_lemmas() + '\n' + '\n'.join(lemmas)
    gname = group + ('_' + os.environ['ITEM'] if os.environ.get('ITEM') else '')
    open('../x/dev/G_%s.v' % gname, 'w', newline='\n').write(text)
    print('wrote G_%s.v %d bytes (%.0fs)' % (group, len(text), time.time() - t0))
if __name__ == '__main__':
    main(sys.argv[1])
