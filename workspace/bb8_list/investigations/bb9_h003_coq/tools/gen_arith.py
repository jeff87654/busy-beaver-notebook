"""Generate x/dev/HArith.v: the residue arithmetic of h003's top chain (all divisions exact, K0..K4 mod 5 = 4,3,1,1,0,
K4 = 10h+15).  Every accumulator X in {B, Rd0, Rc1, Ra2, Ra3} is X = M qX + rho (Res.v).  (Adapted from bb9_c7_coq.)"""
import idle
from fractions import Fraction as F
M = 15820312500000; rho = 5059528974366
V = ['qb', 'qd0', 'qc1', 'qa2', 'qa3']
def var(name): d = {v: F(0) for v in V}; d[name] = F(M); d['c'] = F(rho); return d
def lin(*terms):
    out = {v: F(0) for v in V}; out['c'] = F(0)
    for coef, x in terms:
        if isinstance(x, dict):
            for k in out: out[k] += coef * x[k]
        else: out['c'] += coef * x
    return out
def div(x, d, name):
    y = {k: v / d for k, v in x.items()}
    for k, v in y.items(): assert v.denominator == 1, (name, k, v)
    return y
b, rd0, rc1, ra2, ra3 = (var(v) for v in V)
Q = {}
Q['k0'] = div(lin((12, b), (13, 1)), 5, 'k0')
Q['k1'] = div(lin((12, rd0), (3, Q['k0']), (-5, 1)), 5, 'k1')
Q['k2'] = div(lin((12, rc1), (3, Q['k1'])), 5, 'k2')
Q['k3'] = div(lin((12, ra2), (9, Q['k2']), (16, 1)), 5, 'k3')
Q['h'] = div(lin((12, ra3), (9, Q['k3']), (12, 1)), 10, 'h')
for k, v in Q.items():
    assert v['c'] > 10 ** 6 and all(v[x] >= 0 for x in V), (k, v)
def zexpr(v):
    s = '%d' % v['c']
    for x in V:
        if v[x]: s += ' + %d * %s' % (v[x], x)
    return '(' + s + ')'
eqs = ['12 * B + 27 = 5 * k0 + 14', '12 * Rd0 + 3 * k0 + 8 = 5 * k1 + 13', '12 * Rc1 + 3 * k1 + 11 = 5 * k2 + 11',
       '12 * Ra2 + 9 * k2 + 27 = 5 * k3 + 11', '12 * Ra3 + 9 * k3 + 27 = 10 * h + 15',
       '1000 <= k0', '1000 <= k1', '1000 <= k2', '1000 <= k3', '1000 <= h']
names = list(Q)
out = ['(** * HArith.v : the residue arithmetic of h003\'s top chain (generated by tools/gen_arith.py).',
       '    With every accumulator = rho (mod Mres) (Res.v), all divisions along the chain are exact and the tops',
       '    K0 = 12B+27, K1, K2, K3, K4 take the branches 4, 3, 1, 1 (mod 5) and then the exit, K4 = 10h + 15. *)',
       'From XL Require Import Individual112.', 'From Coq Require Import Lia PeanoNat List ZArith.', 'Import ListNotations.',
       'Set Default Goal Selector "!".', 'From XDev Require Import Base G_rules Abs Res.', 'Opaque U arrow.', '',
       'Lemma res_split : forall X : nat, ((Z.of_nat X) mod Mres = rho)%Z -> exists q : Z, (0 <= q)%Z /\ Z.of_nat X = (Mres * q + rho)%Z.',
       'Proof.', '  intros X H. exists (Z.of_nat X / Mres)%Z. split.',
       '  - apply Z.div_pos; unfold Mres; lia.', '  - rewrite <- H. apply Z.div_mod. unfold Mres. lia.', 'Qed.', '',
       'Lemma h_arith : forall B Rd0 Rc1 Ra2 Ra3 : nat,',
       '  ((Z.of_nat B) mod Mres = rho)%Z -> ((Z.of_nat Rd0) mod Mres = rho)%Z -> ((Z.of_nat Rc1) mod Mres = rho)%Z ->',
       '  ((Z.of_nat Ra2) mod Mres = rho)%Z -> ((Z.of_nat Ra3) mod Mres = rho)%Z ->',
       '  exists %s : nat,' % ' '.join(names),
       '    ' + (' /' + chr(92) + chr(10) + '    ').join(eqs) + '.',
       'Proof.',
       '  intros B Rd0 Rc1 Ra2 Ra3 HB H1 H2 H3 H4.',
       '  destruct (res_split B HB) as [qb [Hqb EB]]. destruct (res_split Rd0 H1) as [qd0 [Hq1 E1]].',
       '  destruct (res_split Rc1 H2) as [qc1 [Hq2 E2]]. destruct (res_split Ra2 H3) as [qa2 [Hq3 E3]].',
       '  destruct (res_split Ra3 H4) as [qa3 [Hq4 E4]]. unfold Mres, rho in *.']
for k in names:
    out.append('  pose (w_%s := %s%%Z).' % (k, zexpr(Q[k])))
    out.append('  assert (P_%s : (0 <= w_%s)%%Z) by (unfold w_%s; lia).' % (k, k, k))
    out.append('  pose proof (Z2Nat.id w_%s P_%s) as F_%s.' % (k, k, k))
    out.append('  set (n_%s := Z.to_nat w_%s) in *. clearbody n_%s. unfold w_%s in F_%s. clear P_%s. clearbody w_%s.' % (k, k, k, k, k, k, k))
out.append('  ' + ' '.join('exists n_%s.' % k for k in names))
out.append('  repeat split; lia.')
out.append('Qed.')
open(r'C:\Users\jeffr\Downloads\bb8\bb8_list\investigations\bb9_h003_coq\x\dev\HArith.v', 'w', newline='\n').write('\n'.join(out) + '\n')
print('ok', {k: (int(v['c']) % 10) for k, v in Q.items()})
