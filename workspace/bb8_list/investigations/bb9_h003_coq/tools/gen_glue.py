"""gen_glue.py: write x/dev/G_t1_glue.v: T1a2 = T1a2a ; (Y_ak = Y_xk at x = 2a+3k+18) ; T1a2b, from the generated statements."""
import re
from pathlib import Path
D = Path(__file__).resolve().parents[1] / 'x' / 'dev'
def stmt(f, name):
    s = (D / f).read_text()
    m = re.search(r'^Lemma %s : forall ([a-z ]+), (.*?) -->\+ (.*)\.$' % name, s, re.M)
    return m.group(1), m.group(2), m.group(3)
va, la, ra = stmt('G_t1_T1a2a.v', 'T1a2a')
vb, lb, rb = stmt('G_t1_T1a2b.v', 'T1a2b')
assert va == 'a k t' and set(vb.split()) == {'x', 'k', 't'}, (va, vb)
X = '(2 * a + 3 * k + 18)'
lbx = lb.replace('^^x', '^^' + X); rbx = rb.replace('^^x', '^^' + X)
args = ' '.join(X if v == 'x' else v for v in vb.split())
out = '''(** T1a2 glue (generated by tools/gen_glue.py): T1a2a, then T1a2b at x = 2a + 3k + 18 (the merged far token). *)
From XL Require Import Individual112.
From Coq Require Import Lia PeanoNat List.
Import ListNotations.
Set Default Goal Selector "!".
From XDev Require Import Base Abs.
From XDev Require G_t1_T1a2a G_t1_T1a2b.

Lemma Y_eq : forall a k t, %s = %s.
Proof.
  intros a k t. replace %s with (18 + (2 * a + 3 * k)) by lia.
  rewrite (pow_add [1;0] 18 (2 * a + 3 * k)), (pow_add [1;0] (2 * a) (3 * k)), (pow_mul [1;0] 2 a), (pow_mul [1;0] 3 k).
  reflexivity.
Qed.

Lemma T1a2 : forall a k t, %s -->+ %s.
Proof.
  intros a k t. eapply progress_trans; [apply G_t1_T1a2a.T1a2a |].
  rewrite Y_eq. exact (G_t1_T1a2b.T1a2b %s).
Qed.
''' % (ra, lbx, X, la, rbx, args)
(D / 'G_t1_glue.v').write_text(out, newline='\n')
print('ok', len(out))
