"""gen_endgame.py : write dev/Endgame.v = casc_key for all five keys and the halting theorem.
  keys 37/43 -> AbsSUB3/AbsSUB4 (J=4) -> D0f(14);  key 55 -> step_stop (i=1) -> D0f(14);  key 49 -> AbsSUB5 (J=6) -> D0f(20).
  D0f(14), D0f(20): entry prefix PFX<L>_<E> (G_p<L>_<E>, clean Kgx target) -> classb_tail (CBtail) -> halted H1 config.
  key 31: c04-k31's k31_end, taken as a Section hypothesis here (instantiated in Final.v)."""
import sys
INFO = {14: (7, 4, []), 20: (6, 5, [4])}      # Kc0, DT, key tokens between the counter 6 and D(y)

def pk_lemma(L, E):
    Kc0, DT, kt = INFO[L]
    Kc = Kc0 + E
    suf = '; '.join(['6'] + [str(x) for x in kt] + ['y', 's'])
    Pb = 18 + E
    return f'''Lemma pk{L}_{E} : forall p s t y l,
  D0f t {L} (6 * p + {Pb}) s y l -->+ Kgx (repeat O (6 * p + {Kc}) ++ [2]) [{suf}] O O (t + {DT}) (1 >> l).
Proof.
  intros. refine (prog_eq _ _ _ _ _ _ (PFX{L}_{E} p s t y l)).
  - unfold D0f. replace (6 * p + {Pb}) with ({Pb - 6} + (6 * p + 6)) by lia.
    rewrite (pow_add [0;0;1] {Pb - 6} (6 * p + 6)), (pow_add [0;0;1] (6 * p) 6), (pow_mul [0;0;1] 6 p).
    reflexivity.
  - unfold Kgx, Kx. rewrite map_rep, map_single, <- app_assoc, lftx_app, lftx_rep. cbn [lftx app].
    change (tokd 2) with 7%nat. change (3 * O + 1) with 1%nat. change (3 * O + 2) with 2%nat.
    rewrite (pow_add [0;0;1;1;1;1;1;1] t {DT}), (pow_add [1;0;1] (6 * p) {Kc}), (pow_mul [1;0;1] 6 p).
    reflexivity.
Qed.
'''

def halt_L(L):
    Kc0, DT, kt = INFO[L]
    cases = []
    for E in range(6):
        if L == 14:
            tail = (f'destruct y as [|a]; [lia |].\n'
                    f'    destruct (classb_tail (6 * p + {Kc0 + E}) a s [] (t + {DT}) (1 >> l) (good1 l)) as [La [Ra H]].')
        else:
            tail = (f'destruct (classb_tail (6 * p + {Kc0 + E}) 3 y [s] (t + {DT}) (1 >> l) (good1 l)) as [La [Ra H]].')
        cases.append(f'''  - replace P with (6 * p + {18 + E}) by lia.
    {tail}
    exists La, Ra. eapply progress_trans; [apply pk{L}_{E} | exact H].''')
    return f'''Lemma D0f{L}_halt : forall t P s y l, 18 <= P -> 1 <= y ->
  exists La Ra, D0f t {L} P s y l -->+ ((1 >> La) <{{{{H}}}} Ra).
Proof.
  intros t P s y l HP Hy. destruct (split6 (P - 18)) as [p [E [HE Hp]]].
  destruct E as [|[|[|[|[|[|E]]]]]]; [| | | | | | lia].
''' + '\n'.join(cases) + '\nQed.\n'

HEAD = r'''(** * Endgame.v : casc_key (all five keys) and the halting theorem, generated by gen/gen_endgame.py.
    keys 37/43 -> one generic sub-step to D0f(14); key 55 -> the generic stop (STOP + clearing + ENTRY) to D0f(14);
    key 49 -> one generic sub-step to D0f(20).  D0f(14)/D0f(20) -> entry prefix (G_p14_E / G_p20_E) -> CBtail.classb_tail
    (ESC, DEC6, clear, DEC3, clear, HALT) -> an H1 configuration (H reading 1: tm (H,1) = None).
    key 31 -> agent c04-k31's k31_end, a Section hypothesis here, instantiated in Final.v. *)
From BB8 Require Import Individual92.
From Coq Require Import Lia PeanoNat List Bool.
Import ListNotations.
Set Default Goal Selector "!".
From Dev Require Import Base G_rules G_sub2 G_sub3 G_sub4 G_sub5 G_stop G_entry G_top G_end Abs Lift Orbit Chain
  Cascade Step CBtail G_p14_0 G_p14_1 G_p14_2 G_p14_3 G_p14_4 G_p14_5 G_p20_0 G_p20_1 G_p20_2 G_p20_3 G_p20_4 G_p20_5.
Opaque U arrow.

(** The H1 configuration is halted (tm (H,1) = None), hence halting. *)
Lemma halts_of_H1 : forall (L R : side), halts tm ((1 >> L) <{{H}} R).
Proof. intros. apply halted_halts. reflexivity. Qed.

Lemma halts_reach_H1 : forall c L R, c0 -->* c -> c -->* ((1 >> L) <{{H}} R) -> halts tm c0.
Proof.
  intros c L R H1 H2. eapply halts_evstep; [| exact H1].
  eapply halts_evstep; [apply halts_of_H1 | exact H2].
Qed.

Lemma good1 : forall l, good (1 >> l).
Proof. intro l. left. exists l. reflexivity. Qed.
'''

TAIL = r'''
(** From a reachable D0 moment that leads (by -->+ ) to D0f(14) / D0f(20) with enough parked zeros, the machine halts. *)
Lemma halts_via14 : forall c t P s y l, c0 -->* c -> c -->+ D0f t 14 P s y l -> 18 <= P -> 1 <= y -> halts tm c0.
Proof.
  intros c t P s y l H1 H2 HP Hy. destruct (D0f14_halt t P s y l HP Hy) as [La [Ra H3]].
  apply (halts_reach_H1 c La Ra H1). apply progress_evstep. eapply progress_trans; [exact H2 | exact H3].
Qed.

Lemma halts_via20 : forall c t P s y l, c0 -->* c -> c -->+ D0f t 20 P s y l -> 18 <= P -> 1 <= y -> halts tm c0.
Proof.
  intros c t P s y l H1 H2 HP Hy. destruct (D0f20_halt t P s y l HP Hy) as [La [Ra H3]].
  apply (halts_reach_H1 c La Ra H1). apply progress_evstep. eapply progress_trans; [exact H2 | exact H3].
Qed.

Lemma Pm_ge : 100 <= Pm.
Proof. destruct L1_val as [b [EB E1]]. pose proof (R2_ge Bx). unfold Pm. lia. Qed.

Section Endgame.
  (** key 31 (agent c04-k31, k31/K31_End.v: k31_end gives this plus the ones count). *)
  Hypothesis k31_halt : forall t P s y l, 35 <= P -> exists c, D0f t 32 P s y l -->* c /\ halted tm c.

  Lemma key31 : reachP Pm 31 -> halts tm c0.
  Proof.
    intros [t [P [s [y [l [HR [Hy HP]]]]]]]. pose proof Pm_ge.
    destruct (k31_halt t P s y l ltac:(lia)) as [c [Hc Hh]].
    eapply halts_evstep; [apply halted_halts, Hh |]. eapply evstep_trans; [exact HR | exact Hc].
  Qed.

  Lemma key37 : reachP Pm 37 -> halts tm c0.
  Proof.
    intros [t [P [s [y [l [HR [Hy HP]]]]]]]. pose proof Pm_ge.
    change (S 37) with (5 * 4 + 18) in HR.
    eapply (halts_via14 _ _ _ _ _ _ HR); [apply (AbsSUB3 4 P s t y l ltac:(lia)) | lia | lia].
  Qed.

  Lemma key43 : reachP Pm 43 -> halts tm c0.
  Proof.
    intros [t [P [s [y [l [HR [Hy HP]]]]]]]. pose proof Pm_ge.
    change (S 43) with (5 * 4 + 24) in HR.
    eapply (halts_via14 _ _ _ _ _ _ HR); [apply (AbsSUB4 4 P s t y l ltac:(lia)) | lia | lia].
  Qed.

  Lemma key49 : reachP Pm 49 -> halts tm c0.
  Proof.
    intros [t [P [s [y [l [HR [Hy HP]]]]]]]. pose proof Pm_ge.
    change (S 49) with (5 * 6 + 20) in HR.
    eapply (halts_via20 _ _ _ _ _ _ HR); [apply (AbsSUB5 6 P s t y l ltac:(lia)) | lia | lia].
  Qed.

  Lemma key55 : reachP Pm 55 -> halts tm c0.
  Proof.
    intros [t [P [s [y [l [HR [Hy HP]]]]]]]. pose proof Pm_ge.
    change (S 55) with (5 * (3 * 1 + 2) + 31) in HR.
    destruct (step_stop 1 P s t y l ltac:(lia) Hy) as [R HS].
    eapply (halts_via14 _ _ _ _ _ _ HR); [exact HS | lia | lia].
  Qed.

  Theorem casc_key : forall L, in_keys L = true -> reachP Pm L -> halts tm c0.
  Proof.
    intros L HK. unfold in_keys in HK.
    repeat (apply orb_true_iff in HK; destruct HK as [HK | HK]); apply Nat.eqb_eq in HK; subst L.
    - apply key31.
    - apply key37.
    - apply key43.
    - apply key49.
    - apply key55.
  Qed.

  Theorem c04_halts_from_k31 : halts tm c0.
  Proof.
    destruct L1_props as [H60 [H2 H3]].
    exact (cascade_from_start (halts tm c0) (reachP Pm) (casc_stepP Pm) casc_key L1 H60 H2 H3 reach_top).
  Qed.
End Endgame.
'''

def main(out):
    parts = [HEAD]
    for L in (14, 20):
        for E in range(6):
            parts.append(pk_lemma(L, E))
        parts.append(halt_L(L))
    parts.append(TAIL)
    open(out, 'w', newline='\n').write('\n'.join(parts))
    print('wrote', out)

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '../dev/Endgame.v')
