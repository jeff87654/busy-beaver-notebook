"""Generate x/dev/C7Arith.v: the residue arithmetic of C7's chain (all divisions exact, the cascade residues).
Every accumulator X in {B, R1, R2, R3, R4} is X = M qX + rho (Res.v).  Quantities are linear forms in the q's."""
import idle
from fractions import Fraction as F
M = 15820312500000; rho = 5059528974366
V = ['qb', 'q1', 'q2', 'q3', 'q4']
def var(name): d = {v: F(0) for v in V}; d[name] = F(M); d['c'] = F(rho); return d
def lin(*terms):
    out = {v: F(0) for v in V}; out['c'] = F(0)
    for coef, x in terms:
        if isinstance(x, dict):
            for k in out: out[k] += coef * x[k]
        else: out['c'] += coef * x
    return out
def div(x, d, name):
    y = {k: v / d for k, v in x.items()}
    for k, v in y.items(): assert v.denominator == 1, (name, k, v)
    return y
b, r1, r2, r3, r4 = (var(v) for v in V)
Q = {}
Q['j1'] = div(lin((9, b), (-9, 1)), 5, 'j1')
D3 = lin((12, r1), (3, Q['j1']), (17, 1))
Q['j2'] = div(lin((9, r2), (1, D3), (-19, 1)), 5, 'j2')
D5 = lin((12, r3), (3, Q['j2']), (17, 1))
Q['j3'] = div(lin((9, r4), (1, D5), (-21, 1)), 5, 'j3')
N = lin((3, Q['j3']), (19, 1))
Q['m'] = div(N, 5, 'm')
L = lin((9, Q['m']), (-7, 1))
steps = [('J2', 63, 35), ('J3', 60, 32), ('J4', 63, 35), ('J5', 64, 32), ('J6', 60, 32), ('J7', 60, 32), ('J8', 63, 35)]
for name, c, c2 in steps:
    Q[name] = div(lin((1, L), (-c, 1)), 5, name)
    L = lin((3, Q[name]), (c2, 1))
Q['u'] = div(lin((1, L), (-17, 1)), 15, 'u')
Q['jj'] = div(lin((1, Q['u']), (-2, 1)), 5, 'jj')
for k, v in Q.items():
    assert v['c'] > 10 ** 6 and all(v[x] >= 0 for x in V), (k, v)
def zexpr(v):
    s = '%d' % v['c']
    for x in V:
        if v[x]: s += ' + %d * %s' % (v[x], x)
    return '(' + s + ')'
eqs = ['9 * B = 5 * j1 + 9', '9 * R2 + 12 * R1 + 3 * j1 + 17 = 5 * j2 + 19', '9 * R4 + 12 * R3 + 3 * j2 + 17 = 5 * j3 + 21',
       '3 * j3 + 19 = 5 * m', '9 * m = 5 * J2 + 70', '3 * J2 + 35 = 5 * J3 + 60', '3 * J3 + 32 = 5 * J4 + 63',
       '3 * J4 + 35 = 5 * J5 + 64', '3 * J5 + 32 = 5 * J6 + 60', '3 * J6 + 32 = 5 * J7 + 60', '3 * J7 + 32 = 5 * J8 + 63',
       '3 * J8 + 35 = 15 * u + 17', 'u = 5 * jj + 2', '1000 <= j1', '1000 <= jj']
names = list(Q)
out = ['(** * C7Arith.v : the residue arithmetic of C7\'s run (generated by tools/gen_arith.py).',
       '    With every accumulator = rho (mod Mres) (Res.v), all divisions by 5 along the chain are exact, the cascade',
       '    takes the branches r = 1 (entry), 3, 0, 3, 4, 0, 0, 3, and then r = 2 with L9 = 15u+17, u = 5jj+2 (the halt). *)',
       'From XL Require Import Individual112.', 'From Coq Require Import Lia PeanoNat List ZArith.', 'Import ListNotations.',
       'Set Default Goal Selector "!".', 'From XDev Require Import Base G_rules Abs Res.', 'Opaque U arrow.', '',
       'Lemma res_split : forall X : nat, ((Z.of_nat X) mod Mres = rho)%Z -> exists q : Z, (0 <= q)%Z /\ Z.of_nat X = (Mres * q + rho)%Z.',
       'Proof.', '  intros X H. exists (Z.of_nat X / Mres)%Z. split.',
       '  - apply Z.div_pos; unfold Mres; lia.', '  - rewrite <- H. apply Z.div_mod. unfold Mres. lia.', 'Qed.', '',
       'Lemma c7_arith : forall B R1 R2 R3 R4 : nat,',
       '  ((Z.of_nat B) mod Mres = rho)%Z -> ((Z.of_nat R1) mod Mres = rho)%Z -> ((Z.of_nat R2) mod Mres = rho)%Z ->',
       '  ((Z.of_nat R3) mod Mres = rho)%Z -> ((Z.of_nat R4) mod Mres = rho)%Z ->',
       '  exists %s : nat,' % ' '.join(names),
       '    ' + (' /' + chr(92) + chr(10) + '    ').join(eqs) + '.',
       'Proof.',
       '  intros B R1 R2 R3 R4 HB H1 H2 H3 H4.',
       '  destruct (res_split B HB) as [qb [Hqb EB]]. destruct (res_split R1 H1) as [q1 [Hq1 E1]].',
       '  destruct (res_split R2 H2) as [q2 [Hq2 E2]]. destruct (res_split R3 H3) as [q3 [Hq3 E3]].',
       '  destruct (res_split R4 H4) as [q4 [Hq4 E4]]. unfold Mres, rho in *.']
for k in names:
    out.append('  pose (w_%s := %s%%Z).' % (k, zexpr(Q[k])))
    out.append('  assert (P_%s : (0 <= w_%s)%%Z) by (unfold w_%s; lia).' % (k, k, k))
    out.append('  pose proof (Z2Nat.id w_%s P_%s) as F_%s.' % (k, k, k))
    out.append('  set (n_%s := Z.to_nat w_%s) in *. clearbody n_%s. unfold w_%s in F_%s. clear P_%s. clearbody w_%s.' % (k, k, k, k, k, k, k))
out.append('  ' + ' '.join('exists n_%s.' % k for k in names))
out.append('  repeat split; lia.')
out.append('Qed.')
open(r'C:\Users\jeffr\Downloads\bb8\bb8_list\investigations\bb9_c7_coq\x\dev\C7Arith.v', 'w', newline='\n').write('\n'.join(out) + '\n')
print('ok', {k: (int(v['c']) % 5) for k, v in Q.items()})
