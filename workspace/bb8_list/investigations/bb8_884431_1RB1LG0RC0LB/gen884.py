"""Generate the phase-lemma part of the Coq proof for 1RB1LG_0RC0LB_1RD0LA_1LE0RH_1RF1RE_0LA0LG_1LC1LA_---0RE.
   python gen884.py OUT_phases.v"""
import os, sys
NL = chr(10)
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import planner8 as pl
from planner8 import drive
from coqgen_util import crossing_lemma, table, cl
import phases884 as P

def script_to_coq2(script):
    out = []
    ops = list(script)
    pre = []
    if ops[0] == ('steps', 0) and ops[1][0] == 'align':
        kind, x0, xs, cnt = ops[1][1]
        c = pl.cnt_str(cnt)
        assert c.isidentifier(), c
        pre.append('rewrite (align_lpow %d %s _ %s). simpl app.' % (x0, cl(xs), c))
        ops = ops[2:]
    first = True
    i = 0
    while i < len(ops):
        op = ops[i]
        if op[0] == 'steps':
            nxt = ops[i + 1]
            exact = nxt[0] == 'lemma'
            if first:
                if op[1] == 0:
                    raise RuntimeError('progress phase must start with a literal step')
                out.append('start_progress.')
            else:
                out.append('execute.')
            first = False
            if nxt[0] == 'cross':
                out.extend(['follow %s.' % nxt[1]] * nxt[2])
            elif nxt[0] == 'align':
                kind, x0, xs, cnt = nxt[1]
                c = pl.cnt_str(cnt)
                if '+' in c or not c.isidentifier():
                    raise RuntimeError('align on composite count %r' % (cnt,))
                if kind == 'ALIGN':
                    out.append('rewrite (align_lpow %d %s _ %s). simpl app.' % (x0, cl(xs), c))
                else:
                    out.append('rewrite (align_lpow_const %d %s %s). simpl app.' % (x0, cl(xs), c))
            else:
                raise RuntimeError('unexpected op %r' % (nxt,))
            i += 2
        elif op[0] == 'end':
            if first:
                out.append('start_progress.')
                first = False
            else:
                out.append('do %d step. finish_norm.' % op[1])
            i += 1
        else:
            raise RuntimeError('stuck: %r' % (op,))
    return pre + out

def gen(outp):
    pl.set_tm(P.TM)
    pl.LEMMAS.clear()
    bodies = []
    for name, (start, target) in P.PH.items():
        if name == 'ZONE':
            continue
        script, _ = drive(name, start, target, matchers=(), maxev=400, verbose=False)
        if script[-1][0] != 'end':
            raise SystemExit('planner did not reach target of %s: %r' % (name, script[-3:]))
        tac = script_to_coq2(script)
        body = 'Lemma %s : %s.\nProof.\n  intros.\n' % (name, P.stmt(start, target))
        line = '  '
        for t in tac:
            if len(line) + len(t) > 100:
                body += line.rstrip() + NL
                line = '  '
            line += t + ' '
        body += line.rstrip() + '\nQed.\n'
        bodies.append(body)
        nst = sum(o[1] for o in script if o[0] in ('steps', 'end'))
        print('  %-6s literal steps %4d, ops %d' % (name, nst, len(script)), file=sys.stderr)
    crossings = ''.join(crossing_lemma(nm, pl.LEMMAS[nm]) + NL for nm in sorted(pl.LEMMAS))
    text = '(** ** Crossing lemmas (generated) *)\n\n' + crossings \
        + '\n(** ** Phase lemmas (scripts generated by the planner) *)\n\n' + '\n'.join(bodies)
    open(outp, 'w', newline=NL).write(text)
    print('wrote', outp, file=sys.stderr)

if __name__ == '__main__':
    gen(sys.argv[1])
