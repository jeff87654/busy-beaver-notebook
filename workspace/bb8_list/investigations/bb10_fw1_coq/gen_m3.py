"""Generate the machine-level lemmas of the M3 halting proof.
  python gen_m3.py PART,PART,...   explore the parts and cache them (gen_cache/PART.pkl)
  python gen_m3.py --write         assemble proofs/BB10_fw1_parts.v (all but stage 0) and proofs/BB10_fw1_st0.v
Parts: see LIST; the specs are in parts.py (PARTS) and specs() below."""
import sys, time, pickle, os
from parts import *
import st0
PROOFS = HERE.parents[1] / 'proofs'
LIST = ['R1t', 'R2t', 'R3t', 'ST0', 'ST1', 'S2x5', 'S3', 'S4', 'S2A', 'S2R', 'H1', 'WRodd', 'H2']
GROUP_A = [n for n in LIST if n not in ('ST0',)]
GROUP_B = ['ST0']
nxt = [V('l')]          # the rest of the word right after the token
NL = '\n'


def specs():
    P = {}
    P['R1t'] = (K([nxt], tok(3, a=1), tok(0, r=1)), K([nxt], tok(0, a=1), tok2(5, r=1)), ())
    P['R2t'] = (K([tok(3, m=1), nxt], tok(1), tok(0, r=1)), K([tok(0, m=1), nxt], tok2(5, r=1), tok(1)), ())
    P['R3t'] = (K([zeros(M=1), tok(1), tok(3, m=1), nxt], tok(1), tok(0, r=1)),
                K([zeros(M=1), tok2(5, r=1), tok(0, m=1), nxt], tok(1), tok(1)), ())
    for n in ('ST1', 'S2x5', 'S3', 'S4', 'S2A', 'H1', 'WRodd'):
        P[n] = PARTS[n]
    P['S2R'] = PARTS['S2Rv0']
    P['H2'] = PARTS['H2free']
    return P


def gen_one(name, s, t, pos, bounds=None, splits=6):
    t0 = time.time()
    tree = mexp.explore(s, t, positive=frozenset(pos), maxstages=600, splits=splits)
    if t is None:
        assert 'end' in tree and tree.get('halt'), 'halting part must end at the root'
        t = tree['end']
    g = mexp.Gen(name)
    lem = mexp.rule_lemma(name, s, t, tree, g, progress=False, positive=pos, bounds=bounds)
    print('%s: %d lemmas (%.1fs)' % (name, len(g.lemmas), time.time() - t0), file=sys.stderr, flush=True)
    return g.lemmas + [lem], (s, t)


def explore_parts(which):
    P = specs()
    cache = HERE / 'gen_cache'
    cache.mkdir(exist_ok=True)
    for name in which:
        pl.LEMMAS.clear()
        if name == 'ST0':
            T0 = pickle.load(open(HERE / 'ST0_T.pkl', 'rb'))
            out = gen_one(name, PARTS['ST0free'][0], T0, ('M', 'b'))
        elif name == 'ST0a':
            W0 = pickle.load(open(HERE / 'W0.pkl', 'rb')) if os.path.exists(HERE / 'W0.pkl') else st0.find_w0()
            out = gen_one(name, PARTS['ST0free'][0], W0, ('M', 'b'))
        elif name == 'ST0b':
            W0 = pickle.load(open(HERE / 'W0.pkl', 'rb'))
            W1 = st0.merge_zeros(W0)
            T = K([zeros(Z=1), tok(1) * 15, tok(5), tok(0), tok(2), tok(2), [run(tuple(tok(6)) * 4, b=1)], tok(6) * 2, [BLANK]],
                  tok(1), tok(1))
            out = gen_one(name, W1, T, ('Z', 'b'), bounds={'Z': 24}, splits=30)
        else:
            s, t, pos = P[name]
            out = gen_one(name, s, t, pos)
        crosses = {nm: pl.LEMMAS[nm] for nm in pl.LEMMAS}
        pickle.dump((out, crosses), open(cache / ('%s.pkl' % name), 'wb'))


def assemble_group(names, have):
    import coqgen_util
    cache = HERE / 'gen_cache'
    lemmas, crosses = [], {}
    for name in names:
        f = cache / ('%s.pkl' % name)
        if not f.exists():
            print('missing', name, file=sys.stderr)
            continue
        (lems, st), cr = pickle.load(open(f, 'rb'))
        lemmas.extend(lems)
        crosses.update(cr)
    cl = ''.join(coqgen_util.crossing_lemma(nm, crosses[nm]) + NL for nm in sorted(crosses) if nm not in have)
    return cl + NL + NL.join(lemmas), crosses


def assemble():
    textA, crA = assemble_group(GROUP_A, {})
    hdr = header('Machine-level lemmas for the BB(10) candidate %s' % TM)
    hdr = hdr.replace('From BB8 Require Import Individual102.', 'From BB8 Require Export Individual102.')
    open(PROOFS / 'BB10_fw1_parts.v', 'w', newline=NL).write(hdr + NL + textA)
    textB, _ = assemble_group(GROUP_B, crA)
    hb = ('(** * Stage-0 machine-level lemmas for the BB(10) candidate %s *)' % TM + NL + NL +
          '(** Generated by bb8_list/investigations/bb10_fw1_coq/gen_m3.py (explorer: mexp.py). *)' + NL + NL +
          'From BB8 Require Export BB10_fw1_parts.' + NL + 'From Coq Require Import Lia PeanoNat List.' + NL +
          'Import ListNotations.' + NL + 'Set Default Goal Selector "!".' + NL + NL)
    open(PROOFS / 'BB10_fw1_st0.v', 'w', newline=NL).write(hb + textB)
    print('wrote BB10_fw1_parts.v and BB10_fw1_st0.v', file=sys.stderr)


if __name__ == '__main__':
    if sys.argv[1] == '--write':
        assemble()
    else:
        explore_parts(sys.argv[1].split(','))
