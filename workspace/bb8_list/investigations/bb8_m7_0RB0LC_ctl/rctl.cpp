// rctl: MitM closed-tape-language search with a run-length side abstraction (single-cell head, no blocks).
// Side summary (cells pushed from the far end towards the head): list of runs (bit, abstract count);
// the first TA runs (far end) are anchors and never dropped; after them at most H runs are kept (the nearest);
// when more accumulate the farthest non-anchor run is dropped. Count abstraction per bit: exact up to K[b],
// then "big" with residue mod M[b].  Leading zeros at the far end are ignored (empty side = all blank).
// Abstract config (l, q, s, r).  Sound by construction: side languages are generated by observed pushes.
//   rctl MACHINE TA H K0 K1 M0 M1 MAXCFG [certfile]
#include <bits/stdc++.h>
using namespace std;
struct Tr { int w, d, q; bool ok; };
static Tr tm_[8][2]; static int NS = 0;
static int TA, H, K[2], Mo[2];
typedef vector<uint16_t> Sum;  // each run encoded as bit<<15 | code ; code = 1..K exact, K+1+res big
static unordered_map<string, int> idOf; static vector<Sum> sums;
static string keyOf(const Sum& s) { return string((const char*)s.data(), s.size() * 2); }
static int intern(const Sum& s) {
  auto k = keyOf(s); auto it = idOf.find(k); if (it != idOf.end()) return it->second;
  int id = sums.size(); sums.push_back(s); idOf.emplace(k, id); return id;
}
static uint16_t inc(int b, uint16_t c) {
  if (c < K[b]) return c + 1;
  if (c == K[b]) return K[b] + 1 + ((K[b] + 1) % Mo[b]);
  int res = c - K[b] - 1; return K[b] + 1 + ((res + 1) % Mo[b]);
}
static Sum pushS(const Sum& s, int b) {
  Sum t = s;
  if (t.empty()) { if (b == 0) return t; t.push_back((1 << 15) | 1); return t; }
  int lb = t.back() >> 15;
  if (lb == b) { t.back() = (b << 15) | inc(b, t.back() & 0x7fff); return t; }
  t.push_back((b << 15) | 1);
  if ((int)t.size() > TA + H) t.erase(t.begin() + TA);
  return t;
}
static string showS(const Sum& s, bool rev) {
  string o; vector<string> parts;
  for (auto e : s) { int b = e >> 15, c = e & 0x7fff; string p = to_string(b) + "^" + (c <= K[b] ? to_string(c) : ("B" + to_string(c - K[b] - 1))); parts.push_back(p); }
  if (rev) reverse(parts.begin(), parts.end());
  for (auto& p : parts) o += p + " ";
  return o;
}
// push table and pop lists
static unordered_map<uint64_t, int> pushT; static vector<vector<pair<int, int>>> pops;  // pops[s] = list of (prev, bit)
static vector<vector<uint64_t>> waitL, waitR;  // configs waiting on popping a side state (as left side / right side)
static int pushId(int id, int b, vector<int>& newEdges) {
  uint64_t k = ((uint64_t)id << 1) | b; auto it = pushT.find(k); if (it != pushT.end()) return it->second;
  Sum t = pushS(sums[id], b); int nid = intern(t);
  if ((int)pops.size() < (int)sums.size()) { pops.resize(sums.size()); waitL.resize(sums.size()); waitR.resize(sums.size()); }
  pushT.emplace(k, nid);
  pops[nid].push_back({id, b}); newEdges.push_back(nid);
  return nid;
}
// config key
static inline uint64_t ck(int l, int q, int s, int r) { return ((uint64_t)l << 34) | ((uint64_t)r << 4) | (q << 1) | s; }
static unordered_map<uint64_t, uint64_t> parent; static deque<uint64_t> work;
static void add(uint64_t c, uint64_t par) { if (parent.emplace(c, par).second) work.push_back(c); }
static void decode(uint64_t c, int& l, int& q, int& s, int& r) { l = c >> 34; r = (c >> 4) & ((1u << 30) - 1); q = (c >> 1) & 7; s = c & 1; }
static string showC(uint64_t c) { int l, q, s, r; decode(c, l, q, s, r); return showS(sums[l], false) + " [" + char('A' + q) + to_string(s) + "] " + showS(sums[r], true); }
int main(int argc, char** argv) {
  string ms = argv[1]; TA = atoi(argv[2]); H = atoi(argv[3]); K[0] = atoi(argv[4]); K[1] = atoi(argv[5]); Mo[0] = atoi(argv[6]); Mo[1] = atoi(argv[7]);
  long long MAXC = atoll(argv[8]); string certf = argc > 9 ? argv[9] : "";
  { stringstream ss(ms); string row; while (getline(ss, row, '_')) { for (int c = 0; c < 2; c++) { string t = row.substr(3 * c, 3); if (t[0] == '-') tm_[NS][c] = {0, 0, 0, false}; else tm_[NS][c] = {t[0] - '0', t[1] == 'R' ? 1 : -1, t[2] - 'A', true}; } NS++; } }
  int E = intern(Sum()); pops.resize(1); waitL.resize(1); waitR.resize(1);
  pushT.emplace(((uint64_t)E << 1) | 0, E); pops[E].push_back({E, 0});
  add(ck(E, 0, 0, E), ~0ULL);
  vector<int> newEdges; long long iter = 0;
  // process: config c; its successor needs pops of the side it moves into
  auto process = [&](uint64_t c, int onlyPrev, int onlyBit, int edgeState) -> bool {
    int l, q, s, r; decode(c, l, q, s, r);
    Tr t = tm_[q][s];
    if (!t.ok) {
      printf("FAIL: halting abstract config reachable\n");
      vector<uint64_t> path; uint64_t x = c; while (x != ~0ULL) { path.push_back(x); x = parent[x]; }
      reverse(path.begin(), path.end());
      int from = max(0, (int)path.size() - 400);
      for (int i = from; i < (int)path.size(); i++) printf("%5d %s\n", i, showC(path[i]).c_str());
      return false;
    }
    if (t.d == 1) {
      int nl = pushId(l, t.w, newEdges);
      if (edgeState < 0) { waitR[r].push_back(c); for (auto [pr, b] : pops[r]) add(ck(nl, t.q, b, pr), c); }
      else add(ck(nl, t.q, onlyBit, onlyPrev), c);
    } else {
      int nr = pushId(r, t.w, newEdges);
      if (edgeState < 0) { waitL[l].push_back(c); for (auto [pl, b] : pops[l]) add(ck(pl, t.q, b, nr), c); }
      else add(ck(onlyPrev, t.q, onlyBit, nr), c);
    }
    return true;
  };
  while (!work.empty() || !newEdges.empty()) {
    if (!newEdges.empty()) {
      int st = newEdges.back(); newEdges.pop_back();
      auto [pv, b] = pops[st].back();  // the edge just added (edges are appended once)
      // note: multiple edges into st may have been added; handle all pending by re-scan of last edge only is unsafe; use index
      (void)pv; (void)b;
      continue;
    }
    break;
  }
  // simpler robust scheme: iterate until fixpoint, re-processing configs whose waited state gained edges
  vector<size_t> seenEdgesL, seenEdgesR;  // per config? too big; instead per state track processed edge counts per waiting list
  // per state: number of edges already propagated to its waiters
  vector<size_t> propL, propR;
  while (true) {
    while (!work.empty()) {
      uint64_t c = work.front(); work.pop_front();
      if (!process(c, -1, -1, -1)) return 1;
      if ((long long)parent.size() > MAXC) { printf("GIVEUP: %zu configs, %zu side states\n", parent.size(), sums.size()); return 2; }
      if (++iter % 1000000 == 0) fprintf(stderr, "iter %lld cfgs %zu sides %zu\n", iter, parent.size(), sums.size());
    }
    // propagate new edges to waiters
    bool any = false;
    propL.resize(sums.size(), 0); propR.resize(sums.size(), 0);
    for (size_t st = 0; st < sums.size(); st++) {
      if (st >= pops.size()) break;
      size_t ne = pops[st].size();
      // waiters registered before: they processed edges [0, prop) at registration time? No: at registration they saw pops[st] fully.
      // To be safe, re-process every waiter against every edge index >= the count recorded at last propagation.
      if (propL[st] < ne) {
        for (size_t wi = 0; wi < waitL[st].size(); wi++) { uint64_t c = waitL[st][wi]; int l, q, s, r; decode(c, l, q, s, r); Tr t = tm_[q][s];
          int nr = pushId(r, t.w, newEdges); for (size_t ei = propL[st]; ei < ne; ei++) { auto [pl, b] = pops[st][ei]; add(ck(pl, t.q, b, nr), c); } }
        propL[st] = ne; any = true;
      }
      if (propR[st] < ne) {
        for (size_t wi = 0; wi < waitR[st].size(); wi++) { uint64_t c = waitR[st][wi]; int l, q, s, r; decode(c, l, q, s, r); Tr t = tm_[q][s];
          int nl = pushId(l, t.w, newEdges); for (size_t ei = propR[st]; ei < ne; ei++) { auto [pr, b] = pops[st][ei]; add(ck(nl, t.q, b, pr), c); } }
        propR[st] = ne; any = true;
      }
    }
    newEdges.clear();
    if (work.empty() && !any) break;
    if (work.empty()) {
      // check whether every state's edges are fully propagated
      bool done = true; for (size_t st = 0; st < pops.size(); st++) if (propL[st] < pops[st].size() || propR[st] < pops[st].size()) { done = false; break; }
      if (done) break;
    }
  }
  printf("CLOSED: %zu abstract configs, %zu side states, %zu push edges\n", parent.size(), sums.size(), pushT.size());
  if (!certf.empty()) {
    FILE* f = fopen(certf.c_str(), "w");
    fprintf(f, "sides %zu\n", sums.size());
    for (auto& [k, v] : pushT) fprintf(f, "e %llu %d %d\n", (unsigned long long)(k >> 1), (int)(k & 1), v);
    for (auto& [c, p] : parent) { int l, q, s, r; decode(c, l, q, s, r); fprintf(f, "c %d %d %d %d\n", l, q, s, r); }
    fclose(f);
  }
  return 0;
}
