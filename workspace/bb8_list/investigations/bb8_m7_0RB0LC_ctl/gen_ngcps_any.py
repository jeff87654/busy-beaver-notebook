"""gen_ngcps_any.py MACHINE CERT OUT.v [NCONFIGS]: the n-gram closed-position-set proof of gen_ngcps_v.py for ANY
8-state machine (Individual82 setup).

CERT is the dump of `ngcps2.exe MACHINE nL nR CERT` (run with NOC=1 to skip the C lines). The Coq file embeds the
window sets, recomputes the local-configuration set inside Coq (bsearch, fuel sized from NCONFIGS, the count printed
by ngcps2) and checks it with the generic `check`, whose soundness (`nonhalt_of_check`) is proved in the file.
Only the title, the comment and the `tm` table differ from the template, which is read from gen_ngcps_v.py.
"""
import math
import re
import sys
from pathlib import Path

machine, cert, out = sys.argv[1], sys.argv[2], sys.argv[3]
nconf = int(sys.argv[4]) if len(sys.argv) > 4 else 1 << 22
rows = machine.split('_')
assert len(rows) == 8 and all(len(r) == 6 for r in rows), 'need an 8-state machine string'

src = (Path(__file__).with_name('gen_ngcps_v.py')).read_text(encoding='utf-8')
tmpl = src[src.index("V = r'''") + len("V = r'''"):src.index("''' % dict(")]

# 1. title and prose: generic description instead of the m7 machine's epoch story
head_end = tmpl.index('From BB8 Require Import Individual82.')
tmpl = (f'(** * {machine} never halts *)\n\n'
        '(** Generated by bb8_list/investigations/bb8_m7_0RB0LC_ctl/gen_ngcps_any.py from an ngcps2.exe certificate.\n\n'
        '    Proof by an n-gram closed position set ("NGramCPS"), the method of BB8_m7_1RB0RA_0RB0LC.v:\n'
        '    - [LS] is a set of left windows (the [nL] = %(nL)d cells left of the head, nearest first) and [RS] a set of\n'
        '      right windows (the [nR] = %(nR)d cells right of the head), embedded below as data.\n'
        '    - [C], a set of local configurations (state, scanned symbol, left window, right window), is computed\n'
        '      inside Coq by a search from the blank tape ([bsearch]).\n'
        '    - [Inv]: every length-[nL] window of the left side lies in [LS], every length-[nR] window of the right side\n'
        '      lies in [RS], and the local configuration lies in [C].\n'
        '    - [check] verifies that [C] contains the blank start, that no member of [C] is halting and that every\n'
        '      successor (for both values of the cell entering the far end of a window) stays in [C], [LS], [RS];\n'
        '      [inv_step] and [nonhalt_of_check] prove that this makes [Inv] closed, so the machine never halts. *)\n\n'
        + tmpl[head_end:])

# 2. the transition table
def entry(q, s, t):
    rhs = 'None' if t == '---' or t[2] == 'Z' else f'Some ({t[0]}, {t[1]}, {t[2]})'
    return f'{q}, {s} => {rhs}'
lines = []
for i, r in enumerate(rows):
    q = 'ABCDEFGH'[i]
    a, b = entry(q, 0, r[:3]), entry(q, 1, r[3:])
    lines.append(f'  | {a:<24}| {b}')
table = '(* machine: %s *)\nDefinition tm : TM := fun \'(q, s) =>\n  match q, s with\n%s\n  end.' % (machine, '\n'.join(lines))
tmpl, n = re.subn(r"\(\* machine: [^*]*\*\)\nDefinition tm : TM := fun '\(q, s\) =>\n  match q, s with\n.*?\n  end\.",
                  lambda _: table.replace('%', '%%'), tmpl, count=1, flags=re.S)
assert n == 1, 'tm block not found in the template'
assert '1RB0RA_1LC1LF' not in tmpl or machine.startswith('1RB0RA_1LC1LF'), 'template still names the m7 machine'

# 3. certificate data and fuel (biter n performs 2^n queue steps)
lines_c = Path(cert).read_text().split('\n')
nL, nR = map(int, lines_c[0].split())
LS = [int(l.split()[1]) for l in lines_c[1:] if l.startswith('L ')]
RS = [int(l.split()[1]) for l in lines_c[1:] if l.startswith('R ')]
fuel = max(4, math.ceil(math.log2(nconf + 1)) + 1)   # biter n runs 2^n queue steps; +1 margin (too little fuel only makes check fail)

def plist(ks):
    res, cur = [], ''
    for k in ks:
        s = str(k) + '; '
        if len(cur) + len(s) > 110:
            res.append(cur.rstrip()); cur = ''
        cur += s
    res.append(cur.rstrip().rstrip(';'))
    return '\n  '.join(res)

V = tmpl % dict(nL=nL, nR=nR, nL1=nL - 1, nR1=nR - 1, fuel=fuel,
                LS=plist([(1 << nL) | w for w in LS]), RS=plist([(1 << nR) | w for w in RS]))
Path(out).write_text(V, encoding='utf-8', newline='\n')
print('wrote', out, len(V), 'bytes; nL/nR', nL, nR, '|LS|', len(LS), '|RS|', len(RS), 'fuel', fuel)
