"""Derive a gen_digitlist.py spec from the digit-list scan's fit (kfit.py on the mirror image), then generate.

  python auto_spec.py MACHINE KEY OUT.v        KEY as in dl_hits.tsv, e.g. L,A,111,10,0 (orientation,state,suffix,unit,sep)

Supported: keys with orientation L (the structure at the left end of the actual machine, the head on its left),
separator 0, and fitted rules in the DigitListOnes class:
  R1 b -> b + c1 (c1 >= 1);  R2 a = b + c2 - 1, b2 = 0 (c2 >= 2);  R3 refill b + c3 - k, a3 >= 1, b3 = 0, tail of ones;
  R4 rebuilds (P, 1^(b + c4)) with a4 >= 1, b4 = 0 and no zero digit in P.
Anything else is reported as out of class.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS = HERE.parent / 'investigations' / 'neighbors_family_tools'


def mirror(tm):
    return tm.translate(str.maketrans('LR', 'RL'))


def fit(tm, key):
    o, q, suf, u, sep = key.split(',')
    env = dict(os.environ, BB_KENC='%s,%s' % (u, sep))
    m = mirror(tm) if o == 'L' else tm
    r = subprocess.run([sys.executable, str(TOOLS / 'kfit.py'), m, '--shape', '%s,%s' % (q, suf), '--params'],
                       cwd=TOOLS, capture_output=True, text=True, env=env, timeout=600)
    line = next((l for l in r.stdout.splitlines() if l.strip().startswith('params:')), None)
    if line is None:
        raise SystemExit('kfit gave no parameters:\n' + r.stdout[-2000:])
    return json.loads(line.split('params:', 1)[1])


def spec_from(tm, key, P):
    o, q, suf, u, sep = key.split(',')
    why = []
    if o != 'L':
        why.append('orientation R (structure at the right end) is not supported yet')
    if sep != '0':
        why.append('separator %r (only 0 is supported)' % sep)
    need = ['m1', 'c1', 'm2', 'c2', 'b2', 'm3', 'c3', 'a3', 'b3', 'P', 'm4', 'c4', 'a4', 'b4']
    missing = [k for k in need if k not in P]
    if missing:
        why.append('rules not fitted: %s' % missing)
    else:
        if P['m1'] != 1 or P['c1'] < 1:
            why.append('R1 is not b -> b + c1 with c1 >= 1')
        if P['m2'] != 1 or P['c2'] < 1 or P['b2'] != 0:
            why.append('R2 is not a = b + c2 - 1 (c2 >= 2) with b2 = 0')
        if P['m3'] != 1 or P['c3'] < 1 or P['a3'] < 1 or P['b3'] != 0:
            why.append('R3 is not refill b + c3 - k with a3 >= 1 and b3 = 0')
        if P['m4'] != 1 or P['a4'] < 1 or P['b4'] != 0 or any(d <= 0 for d in P['P']) or 1 + P['c4'] < 0:
            why.append('R4 is not (P, 1^(b + c4)) with a4 >= 1, b4 = 0 and positive P')
    if why:
        return None, why
    # machine coordinates: the actual tape right of the head is the mirror word reversed, the head on a blank
    unit = [int(c) for c in reversed(u)]
    Pm = [0] + [int(c) for c in reversed(suf)]
    spec = {'tm': tm, 'q': q, 'P': Pm, 'u': unit,
            'c1': P['c1'], 'c2': P['c2'] + 1, 'c3': P['c3'], 'a3': P['a3'],
            'top': [1, 1 + P['c4'], list(reversed(P['P']))], 'a4': P['a4'],
            'title': '%s never halts (generated by bb8_list/autoproof)' % tm}
    return spec, []


def main():
    tm, key, outp = sys.argv[1], sys.argv[2], sys.argv[3]
    P = fit(tm, key)
    spec, why = spec_from(tm, key, P)
    if spec is None:
        print('OUT OF CLASS:', '; '.join(why))
        sys.exit(2)
    sp = Path(outp).with_suffix('.spec.json')
    sp.write_text(json.dumps(spec, indent=1))
    print('spec:', json.dumps(spec))
    subprocess.run([sys.executable, str(HERE / 'gen_digitlist.py'), str(sp), outp], check=True)


if __name__ == '__main__':
    main()
